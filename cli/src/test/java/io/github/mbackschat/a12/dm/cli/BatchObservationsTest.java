/** The deliberately small, deterministic kernel-verdict artifact produced by {@code batch --observations}. */
class BatchObservationsTest {

    private static final ObjectMapper MAPPER = new ObjectMapper();

    @Test
    void writesAByteStableKernelVerdictArtifactInDispatchOrder(@TempDir Path dir) throws Exception {
        Path model = dir.resolve("subscription.dm.json");
        Files.writeString(model, CliTestSupport.subscriptionJson());
        String accepted = "[MonthlyFee] > 1000";
        String rejected = "@@@ junk @@@";
        Path ops = dir.resolve("ops.json");
        Files.writeString(ops, """
                [
                  {"id":"accepted","verb":"rule","args":["check","--field","/Subscription/Addons/MonthlyFee","--condition",%s,"--code","CAP"]},
                  {"id":"rejected","verb":"rule","args":["check","--field","/Subscription/Addons/MonthlyFee","--condition",%s,"--code","SYNTAX"]},
                  {"id":"after-failure","verb":"rule","args":["check","--field","/Subscription/Addons/MonthlyFee","--condition",%s,"--code","AFTER"]}
                ]
                """.formatted(MAPPER.writeValueAsString(accepted), MAPPER.writeValueAsString(rejected),
                        MAPPER.writeValueAsString(accepted)));
        Path observations = dir.resolve("observations.json");
        Files.writeString(observations, "stale generated bytes");

        CliTestSupport.Result first = CliTestSupport.run("-m", model.toString(), "batch", ops.toString(),
                "--observations", observations.toString());

        assertEquals(0, first.code(), first::out);
        JsonNode batch = MAPPER.readTree(first.out());
        assertTrue(batch.path("ok").asBoolean(), "the completed artifact write is the observation operation");
        assertFalse(batch.path("data").path("allExitedZero").asBoolean(),
                "the rejected child remains visible independently of observation success");
        assertTrue(batch.path("written").asBoolean(), "the outer envelope owns the artifact write");
        assertEquals(observations.toAbsolutePath().normalize().toString(), batch.path("output").asText());
        JsonNode artifact = MAPPER.readTree(Files.readString(observations));
        assertEquals(List.of("schemaVersion", "dmtool", "kernelBuilt", "kernelRuntime", "source", "model",
                "observations"), fieldNames(artifact));
        assertEquals(1, artifact.path("schemaVersion").asInt());
        VersionInfo version = VersionInfo.current();
        assertEquals(version.rulekit(), artifact.path("dmtool").asText());
        assertEquals(version.kernelBuiltAgainst(), artifact.path("kernelBuilt").asText());
        assertEquals(version.kernelRuntime(), artifact.path("kernelRuntime").asText());
        assertEquals(version.sourceRevision(), artifact.path("source").path("revision").asText());
        assertEquals(version.sourceState().name(), artifact.path("source").path("state").asText());
        assertEquals(sha256(Files.readAllBytes(model)), artifact.path("model").asText());

        JsonNode recorded = artifact.path("observations");
        assertEquals(3, recorded.size());
        assertEquals(List.of("id", "inputHash", "ok", "valid", "codes"), fieldNames(recorded.get(0)));
        assertEquals("accepted", recorded.get(0).path("id").asText());
        assertEquals(sha256(accepted.getBytes(StandardCharsets.UTF_8)), recorded.get(0).path("inputHash").asText());
        assertTrue(recorded.get(0).path("ok").asBoolean());
        assertTrue(recorded.get(0).path("valid").asBoolean());
        assertEquals(List.of(), MAPPER.convertValue(recorded.get(0).path("codes"), List.class));

        assertEquals("rejected", recorded.get(1).path("id").asText());
        assertEquals(sha256(rejected.getBytes(StandardCharsets.UTF_8)), recorded.get(1).path("inputHash").asText());
        assertTrue(recorded.get(1).path("ok").asBoolean(),
                "a completed kernel gate is ok even when its verdict is invalid");
        assertFalse(recorded.get(1).path("valid").asBoolean());
        assertEquals(codes(batch.path("data").path("results").get(1).path("result")),
                textValues(recorded.get(1).path("codes")), "diagnostic codes retain the kernel's order");
        assertEquals("after-failure", recorded.get(2).path("id").asText());
        assertEquals(0, batch.path("data").path("results").get(2).path("exit").asInt(),
                "dispatch continues after a failed child");

        String firstBytes = Files.readString(observations);
        CliTestSupport.Result second = CliTestSupport.run("-m", model.toString(), "batch", ops.toString(),
                "--observations", observations.toString());
        assertEquals(first.code(), second.code(), second::out);
        assertEquals(firstBytes, Files.readString(observations), "an identical rerun is byte-identical");
        assertFalse(firstBytes.contains(dir.toString()), "the artifact must not retain machine-local paths");
        assertFalse(firstBytes.contains("summary") || firstBytes.contains("duration") || firstBytes.contains("args"));
    }

    @Test
    void hashesExactComputationSpecBytesAndMirrorsOnlyVerdictFields(@TempDir Path dir) throws Exception {
        Path model = dir.resolve("subscription.dm.json");
        Files.writeString(model, CliTestSupport.subscriptionJson());
        Path spec = dir.resolve("computation.json");
        byte[] authored = ("""
                {
                  "computedField": "/Subscription/Billing/EffectiveFee",
                  "name": "ObservedComputation",
                  "alternatives": [ { "operation": "[/Subscription/Billing/BaseFee]" } ],
                  "messages": [
                    { "locale": "en_US", "text": "Observed computation mismatch." },
                    { "locale": "de_DE", "text": "Beobachtete Berechnung weicht ab." }
                  ]
                }

                """).getBytes(StandardCharsets.UTF_8);
        Files.write(spec, authored);
        Path ops = dir.resolve("ops.json");
        Files.writeString(ops, "[{\"id\":\"computation\",\"verb\":\"computation\",\"args\":[\"add\","
                + MAPPER.writeValueAsString(spec.toString()) + ",\"--dry-run\"]}]");
        Path observations = dir.resolve("observations.json");

        CliTestSupport.Result result = CliTestSupport.run("-m", model.toString(), "batch", ops.toString(),
                "--observations", observations.toString());

        assertEquals(0, result.code(), () -> result.out() + result.err());
        JsonNode envelope = MAPPER.readTree(result.out());
        assertTrue(envelope.path("ok").asBoolean());
        assertTrue(envelope.path("data").path("allExitedZero").asBoolean());
        JsonNode child = envelope.path("data").path("results").get(0).path("result");
        JsonNode recorded = MAPPER.readTree(Files.readString(observations)).path("observations").get(0);
        assertEquals(sha256(authored), recorded.path("inputHash").asText());
        assertEquals(child.path("ok").asBoolean(), recorded.path("ok").asBoolean());
        assertEquals(child.has("valid"), recorded.has("valid"));
        if (child.has("valid")) {
            assertEquals(child.path("valid").asBoolean(), recorded.path("valid").asBoolean());
        }
        assertEquals(codes(child), textValues(recorded.path("codes")));
        assertFalse(recorded.has("condition") || recorded.has("spec") || recorded.has("result"));
    }

    @Test
    void refusesAnUndefinedObservationInputBeforeDispatchOrOverwrite(@TempDir Path dir) throws Exception {
        Path model = dir.resolve("subscription.dm.json");
        Files.writeString(model, CliTestSupport.subscriptionJson());
        String before = Files.readString(model);
        Path spec = dir.resolve("field.json");
        Files.writeString(spec,
                "{\"group\":\"/Subscription/Billing\",\"name\":\"MustNotAppear\",\"kind\":\"STRING\"}");
        Path observations = dir.resolve("observations.json");
        Files.writeString(observations, "keep me");

        for (String op : List.of(
                "[{\"verb\":\"rule\",\"args\":[\"check\",\"--field\",\"/Subscription/Billing/BaseFee\",\"--condition\",\"[BaseFee] > 0\"]}]",
                "[{\"id\":\"runtime\",\"verb\":\"rule\",\"args\":[\"eval\",\"--condition\",\"[BaseFee] > 0\",\"--field\",\"/Subscription/Billing/BaseFee\",\"--instance\",\"doc.json\"]}]",
                "[{\"id\":\"text\",\"verb\":\"rule\",\"args\":[\"check\",\"--field\",\"/Subscription/Billing/BaseFee\",\"--condition\",\"[BaseFee] > 0\",\"--code\",\"X\",\"--text\"]}]",
                "[{\"id\":\"write\",\"verb\":\"computation\",\"args\":[\"add\"," + MAPPER.writeValueAsString(spec.toString()) + "]}]",
                "[{\"id\":\"write\",\"verb\":\"field\",\"args\":[\"add\"," + MAPPER.writeValueAsString(spec.toString()) + "]}]")) {
            Path ops = dir.resolve("ops-" + Math.abs(op.hashCode()) + ".json");
            Files.writeString(ops, op);
            CliTestSupport.Result result = CliTestSupport.run("-m", model.toString(), "batch", ops.toString(),
                    "--observations", observations.toString());
            assertEquals(1, result.code(), result::out);
            assertEquals("rejected", MAPPER.readTree(result.out()).path("outcome").asText(), result::out);
            assertEquals(before, Files.readString(model), "observation preflight runs before child zero");
            assertEquals("keep me", Files.readString(observations), "a refused run does not overwrite its artifact");
        }
    }

    @Test
    void neverOverwritesAModelOrAuthoredInputWithTheGeneratedArtifact(@TempDir Path dir) throws Exception {
        Path model = dir.resolve("subscription.dm.json");
        Files.writeString(model, CliTestSupport.subscriptionJson());
        Path spec = dir.resolve("computation.json");
        Files.writeString(spec, """
                {
                  "computedField": "/Subscription/Billing/EffectiveFee",
                  "name": "ProtectedSpec",
                  "alternatives": [{"operation":"[/Subscription/Billing/BaseFee]"}],
                  "messages": [{"locale":"en_US","text":"Protected."},{"locale":"de_DE","text":"Geschützt."}]
                }
                """);
        Path ops = dir.resolve("ops.json");
        Files.writeString(ops, "[{\"id\":\"safe\",\"verb\":\"computation\",\"args\":[\"add\","
                + MAPPER.writeValueAsString(spec.toString()) + ",\"--dry-run\"]}]");
        byte[] modelBefore = Files.readAllBytes(model);
        byte[] opsBefore = Files.readAllBytes(ops);
        byte[] specBefore = Files.readAllBytes(spec);

        Path opsAlias = dir.resolve("ops-alias.json");
        Path modelAlias = dir.resolve("model-alias.json");
        Path specAlias = dir.resolve("spec-alias.json");
        Files.createSymbolicLink(opsAlias, ops.getFileName());
        Files.createSymbolicLink(modelAlias, model.getFileName());
        Files.createSymbolicLink(specAlias, spec.getFileName());

        for (Path destination : List.of(ops, model, spec, opsAlias, modelAlias, specAlias)) {
            CliTestSupport.Result result = CliTestSupport.run("-m", model.toString(), "batch", ops.toString(),
                    "--observations", destination.toString());
            assertEquals(1, result.code(), () -> destination + ": " + result.out());
            assertEquals("rejected", MAPPER.readTree(result.out()).path("outcome").asText(), result::out);
            assertTrue(java.util.Arrays.equals(modelBefore, Files.readAllBytes(model)), "model changed via " + destination);
            assertTrue(java.util.Arrays.equals(opsBefore, Files.readAllBytes(ops)), "ops changed via " + destination);
            assertTrue(java.util.Arrays.equals(specBefore, Files.readAllBytes(spec)), "spec changed via " + destination);
        }
    }

    @Test
    void omitsModelIdentityWhenAnyChildHasNoEffectiveModel(@TempDir Path dir) throws Exception {
        Path model = dir.resolve("subscription.dm.json");
        Files.writeString(model, CliTestSupport.subscriptionJson());
        Path ops = dir.resolve("ops.json");
        Files.writeString(ops, """
                [
                  {"id":"modeled","verb":"rule","args":["check","-m",%s,"--field","/Subscription/Billing/BaseFee","--condition","[BaseFee] > 0","--code","MODELED"]},
                  {"id":"unmodeled","verb":"rule","args":["check","--field","/Subscription/Billing/BaseFee","--condition","[BaseFee] > 0","--code","UNMODELED"]}
                ]
                """.formatted(MAPPER.writeValueAsString(model.toString())));
        Path observations = dir.resolve("observations.json");

        CliTestSupport.Result result = CliTestSupport.run("batch", ops.toString(),
                "--observations", observations.toString());

        assertEquals(0, result.code(), result::out);
        JsonNode artifact = MAPPER.readTree(Files.readString(observations));
        assertFalse(artifact.has("model"), "a hash is common only when every child has the same effective model");
        assertEquals(2, artifact.path("observations").size());
    }

    @Test
    void artifactWriteFailureKeepsChildResultsAndFailsTheWholeObservationInvocation(@TempDir Path dir)
            throws Exception {
        Path model = dir.resolve("subscription.dm.json");
        Files.writeString(model, CliTestSupport.subscriptionJson());
        Path ops = dir.resolve("ops.json");
        Files.writeString(ops, "[{\"id\":\"ran\",\"verb\":\"rule\",\"args\":[\"check\",\"--field\","
                + "\"/Subscription/Billing/BaseFee\",\"--condition\",\"[BaseFee] > 0\",\"--code\",\"RAN\"]}]");
        Path destinationDirectory = Files.createDirectory(dir.resolve("observations"));

        CliTestSupport.Result result = CliTestSupport.run("-m", model.toString(), "batch", ops.toString(),
                "--observations", destinationDirectory.toString());

        assertEquals(70, result.code(), () -> result.out() + result.err());
        JsonNode envelope = MAPPER.readTree(result.out());
        assertFalse(envelope.path("ok").asBoolean());
        assertEquals("error", envelope.path("outcome").asText());
        assertTrue(envelope.path("data").path("dispatched").asBoolean());
        assertEquals(1, envelope.path("data").path("results").size(), "completed child evidence must survive");
        assertEquals(0, envelope.path("data").path("results").get(0).path("exit").asInt());
        assertEquals("RK_INTERNAL_ERROR", envelope.path("diagnostics").get(0).path("code").asText());
        assertFalse(envelope.path("written").asBoolean(), "the artifact write did not complete");
        assertFalse(envelope.has("output"));
    }

    @Test
    void schemaBatchPublishesTheGeneratedArtifactShape(@TempDir Path dir) throws Exception {
        JsonNode batchSchema = MAPPER.readTree(CliTestSupport.run("schema", "batch").out());
        JsonNode artifactSchema = batchSchema.path("observationArtifact");
        assertEquals("BatchObservations", artifactSchema.path("title").asText(), batchSchema::toPrettyString);
        assertTrue(artifactSchema.path("description").asText().contains("diagnostic codes only"));
        assertTrue(artifactSchema.path("required").toString().contains("schemaVersion"));
        assertTrue(artifactSchema.path("required").toString().contains("observations"));

        Path model = dir.resolve("subscription.dm.json");
        Files.writeString(model, CliTestSupport.subscriptionJson());
        Path ops = dir.resolve("ops.json");
        Files.writeString(ops, "[{\"id\":\"valid\",\"verb\":\"rule\",\"args\":[\"check\",\"--field\","
                + "\"/Subscription/Addons/MonthlyFee\",\"--condition\",\"[MonthlyFee] > 1000\","
                + "\"--code\",\"CAP\"]}]");
        Path observations = dir.resolve("observations.json");
        CliTestSupport.Result result = CliTestSupport.run("-m", model.toString(), "batch", ops.toString(),
                "--observations", observations.toString());
        assertEquals(0, result.code(), result::out);
        assertTrue(SpecKeys.forSchema("batch-observations")
                        .validate(MAPPER.readTree(Files.readString(observations))).isEmpty(),
                "a produced observation artifact conforms to the schema served by `schema batch`");
    }

    private static List<String> fieldNames(JsonNode node) {
        return java.util.stream.StreamSupport.stream(
                ((Iterable<String>) () -> node.fieldNames()).spliterator(), false).toList();
    }

    private static List<String> codes(JsonNode envelope) {
        return java.util.stream.StreamSupport.stream(envelope.path("diagnostics").spliterator(), false)
                .map(diagnostic -> diagnostic.path("code").asText())
                .toList();
    }

    private static List<String> textValues(JsonNode array) {
        return java.util.stream.StreamSupport.stream(array.spliterator(), false)
                .map(JsonNode::asText)
                .toList();
    }

    private static String sha256(byte[] input) throws Exception {
        return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(input));
    }
}
