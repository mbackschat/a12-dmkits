/** Exact reserved error key measured by CustomTestRangeLawsTest; case and suffix variants are ordinary rejections. */
internal const val CUSTOM_TEST_RANGE = "testIDNummer"

/**
 * The auto-check emitter + the formal-status oracle — a call-invariant collaborator of the I2 eval-state
 * seam (IF117). Owns the kernel's document-wide autogenerated validations (format errors, `mandatoryField`,
 * `uniqueIndex`, the structural over-repetition checks) AND the single source for "is this operand formally
 * unknown?" ([computeFormalResultAt]), which the rule path (memoized via [FormalResultCache]), the
 * `RepetitionNotUnique` duplicate cache, and the computation engine's poison gate all consult. Allocated
 * once per [DmInterpreter]; the per-call state lives in [ValidationPass].
 */
internal class AutoChecks(
    private val model: ModelDef,
    private val legalCharset: LegalCharset,
    private val predefinedTypes: Map<String, PredefinedType>,
    private val customFieldTypes: Map<String, CustomFieldType>,
    private val patterns: PatternRegistry,
    private val paths: ModelPathIndex,
    private val messageLabel: (String, String, List<Int>) -> String,
) {

    /**
     * One formal-error [Message] per malformed filled field, document-wide — the runtime twin of the
     * kernel's `formalePruefung` checks. Channels match the kernel exactly (code, [FORMAL_RULE_PATH], field
     * pointer, ERROR, VALUE); the human text is the interpreter's own wording ([formalErrorText]), not the
     * kernel's German bundle (KERNEL-INTEGRATION-NOTES "Formal-error message text").
     */
    fun formalErrors(doc: Document, locale: String, isRelevant: Relevance, cache: FormalResultCache,
            customUnsupported: MutableList<UnsupportedRule>): List<Message> =
        doc.valuedFields().filter { isRelevant(it.path, it.reps) }.mapNotNull { vf ->
            when (val result = cache.resultAt(vf.path, vf.reps, vf.raw)) {
                FormalResult.Valid -> null
                is FormalResult.Reported -> formalMessage(
                    result.rejection.code, FORMAL_RULE_PATH, doc.messagePointer(vf.path, vf.reps),
                    MsgType.VALUE, customMessage(result.rejection, vf.path, locale),
                )
                is FormalResult.Unsupported -> {
                    customUnsupported += UnsupportedRule(
                        doc.formattedPointer(vf.path, vf.reps),
                        result.reason,
                        UnsupportedSubject.CELL,
                    )
                    null
                }
                is FormalResult.Invalid -> when (val failure = result.failure) {
                    is FormalFailure.Format -> {
                        val pointer = doc.messagePointer(vf.path, vf.reps)
                        val text = try {
                            formatMessage(failure.error, vf.path, vf.reps, vf.raw, locale)
                        } catch (e: UnsupportedConstructException) {
                            customUnsupported += UnsupportedRule(
                                messagePointerHouseForm(pointer),
                                e.message ?: "unsupported field-owned message",
                                UnsupportedSubject.CELL,
                            )
                            return@mapNotNull null
                        }
                        formalMessage(failure.code, FORMAL_RULE_PATH, pointer, MsgType.VALUE, text)
                    }
                    is FormalFailure.Custom -> formalMessage(
                        failure.code,
                        FORMAL_RULE_PATH,
                        doc.messagePointer(vf.path, vf.reps),
                        MsgType.VALUE,
                        customMessage(failure.rejection, vf.path, locale),
                    )
                    is FormalFailure.OverRepetition -> null
                    is FormalFailure.Generated -> result.reportedRejection?.let { rejection ->
                        formalMessage(rejection.code, FORMAL_RULE_PATH, doc.messagePointer(vf.path, vf.reps),
                            MsgType.VALUE, customMessage(rejection, vf.path, locale))
                    }
                }
            }
        }

    /**
     * One `mandatoryField` [Message] per required-but-empty field instance — the runtime twin of the
     * kernel's autogenerated mandatory rules (KERNEL-FINDINGS §4). The polarity is always OMISSION (filling
     * the field clears it) and the pointer is the field itself. Two shapes, mirroring the kernel's
     * `relativeTo = lowestRepeatableGroupPath`:
     * - **unconditionally** required (mode [Requiredness.ABSOLUTE] with no repeatable ancestor): the field
     *   has exactly one canonical instance (all path parts non-repeatable → indices all 1); the kernel flags
     *   it even on an un-instantiated document, so it is checked directly via [Document.filledAt], not
     *   [Document.contextsFor].
     * - otherwise (absolute under a repeatable ancestor, or relative-to-parent): checked per instantiated row
     *   of the field's [emissionScope], gated by [requiredEmpty]'s `GroupFilled(relativeTo)`.
     */
    fun mandatoryErrors(
        doc: Document,
        locale: String,
        isRelevant: Relevance,
        cache: FormalResultCache,
        unsupported: MutableList<UnsupportedRule>,
    ): List<Message> {
        val out = mutableListOf<Message>()
        for (path in model.requiredFieldPaths) {
            if (model.requirednessOf(path) == Requiredness.ABSOLUTE && lowestRepeatableAncestor(path) == null) {
                val reps = List(pathParts(path).size) { 1 }
                val ctx = doc.onceContextFor(rootGroupOf(path)).single()
                if (isRelevant(path, reps) && cache.hasInvalidCodeAt(path, reps, ctx, MANDATORY_FIELD)) {
                    mandatoryMessage(doc, path, reps, locale, unsupported)?.let(out::add)
                }
            } else {
                for (ctx in doc.instantiatedContextsFor(emissionScope(path))) {
                    val r = ctx.repsOf(path)
                    // An over-limit row's mandatory check is suppressed (it carries the over-repetition code instead).
                    if (isRelevant(path, r) && cache.hasInvalidCodeAt(path, r, ctx, MANDATORY_FIELD)) {
                        mandatoryMessage(doc, path, r, locale, unsupported)?.let(out::add)
                    }
                }
            }
        }
        return out
    }

    /**
     * The `(indexFieldPath, reps)` cells whose value DUPLICATES another row's in the same parent scope — the
     * source for both the `uniqueIndex` messages ([uniquenessMessages]) AND the suppression: a duplicate index
     * is **"unknown"** for any rule referencing it ([formalErrorAt]), branch-scoped exactly like a formal error
     * (verified: a rule on the dup field is suppressed; a rule on a sibling field still fires). Computed once
     * per evaluation and threaded, not recomputed per operand.
     *
     * Cells are compared by their canonical [indexKeyOf] form, never raw text ([IF272]) — a Number index field
     * spelled `5` in one row and `5.00` in another is ONE kernel key, so both rows are flagged.
     */
    fun duplicateIndexCells(
        doc: Document,
        valueAdmissions: ValueAdmissionCache,
        isRelevant: Relevance = ALL_RELEVANT,
    ): Set<Pair<String, List<Int>>> {
        val out = mutableSetOf<Pair<String, List<Int>>>()
        for (indexField in model.indexFields) {
            val rows = doc.instantiatedContextsFor(parentGroup(indexField)).mapNotNull { ctx ->
                val reps = ctx.repsOf(indexField)
                if (paths.overLimitLevel(indexField, reps) != null) return@mapNotNull null   // over-limit rows are suppressed
                // Partial validation: only RELEVANT cells participate in duplicate detection — the kernel builds its
                // index cache from the relevant fields only (`ValidationCommand.befuelleCacheMitRelevantenFeldern`),
                // so a relevant row whose duplicate PARTNER is not relevant is NOT flagged (IF39). Full: all cells.
                if (!isRelevant(indexField, reps)) return@mapNotNull null
                val raw = ctx.displayValue(indexField)?.takeIf { it.isNotEmpty() } ?: return@mapNotNull null
                val admitted = valueAdmissions.participatesInIdentityAt(indexField, reps, raw)
                val candidate = IndexIdentityCandidate(
                    repetitions = reps,
                    key = indexKeyOf(raw, ctx.declaredKind(indexField)).takeIf { admitted },
                    compromises = !admitted,
                )
                reps.dropLast(2) to candidate
            }
            rows.groupBy({ it.first }, { it.second }).forEach { (_, scope) ->
                for (reps in resolveIndexIdentity(scope).duplicateRows) out += indexField to reps
            }
        }
        return out
    }

    /**
     * The DEFAULT-ELIGIBLE index cells of [doc] with their declared S-values — the per-document half of the
     * kernel's `IndexFieldDefaultValueUtils.getIndexFieldIdsEligibleForDefaultValueHandling`
     * (SPEC-2026-07-23-14). A cell is eligible when its field is in [ModelDef.indexDefaults] (enum S-value
     * declared, not explicitly mandatory — the model half), its index group has EXACTLY ONE instantiated row
     * under the current parent, and that row's index cell is clean-empty — physically absent or
     * present-empty. A formally invalid EXPLICIT value is a filled cell, so it is never eligible (the
     * S-value must not paper over it). What the caller does with the cells is phase-specific: full
     * validation and computation STAGE the S-value transiently ([Document.withComputed] — the kernel's
     * `setIndexFieldToDefaultValue`); partial validation marks them silently UNAVAILABLE
     * ([FormalResultCache]'s `unavailable` — the kernel's `markFieldAsInvalidForValidation`).
     */
    fun eligibleIndexDefaults(doc: Document): Map<Pair<String, List<Int>>, String> {
        if (model.indexDefaults.isEmpty()) return emptyMap()
        val out = LinkedHashMap<Pair<String, List<Int>>, String>()
        for ((indexField, sValue) in model.indexDefaults) {
            doc.instantiatedRows(parentGroup(indexField))
                .groupBy { it.dropLast(1) }
                .forEach { (_, rows) ->
                    val row = rows.singleOrNull() ?: return@forEach
                    val cell = row + 1
                    if (!doc.filledAt(indexField, cell)) out[indexField to cell] = sValue
                }
        }
        return out
    }

    /** Full-call message associations may use a singleton default even when its stored value is invalid.
     *  Unlike [eligibleIndexDefaults], these never replace evaluation input (SPEC-2026-10-10-09). */
    fun messageIndexDefaults(doc: Document, admitted: (String, List<Int>, String) -> Boolean): Map<Triple<String, List<Int>, String>, List<Int>> {
        val defaults = LinkedHashMap<Triple<String, List<Int>, String>, List<Int>>()
        for ((field, value) in model.indexDefaults) {
            doc.instantiatedContextsFor(parentGroup(field)).groupBy { it.repsOf(field).dropLast(2) }
                .forEach { (parent, rows) ->
                    val row = rows.singleOrNull() ?: return@forEach
                    val reps = row.repsOf(field)
                    if (paths.overLimitLevel(field, reps) != null) return@forEach
                    val raw = row.displayValue(field)
                    if (raw.isNullOrEmpty() || !admitted(field, reps, raw)) defaults[Triple(field, parent, value)] = reps
                }
        }
        return defaults
    }

    /**
     * The EMPTY index cells the kernel's preliminary index mandatory rule invalidates on the COMPUTE path
     * (SPEC-2026-07-23-15; `CalculationCommand.preliminaryValidationOfIndexFields` →
     * `MainValidatorController.preliminaryError` → `markFieldAsInvalidForValidation`): one entry per
     * instantiated index-group row (post-staging, so a defaulted cell is filled and absent here) whose index
     * cell carries no value. A read of such a cell POISONS the reading computation — unlike an ordinary
     * required-empty field, which stays empty-as-0 (IF76). Over-limit rows keep their over-repetition
     * precedence and are skipped, like every other generated check.
     */
    fun preliminaryEmptyIndexCells(doc: Document): Set<Pair<String, List<Int>>> {
        if (model.indexFields.isEmpty()) return emptySet()
        val out = LinkedHashSet<Pair<String, List<Int>>>()
        for (indexField in model.indexFields) {
            for (row in doc.instantiatedRows(parentGroup(indexField))) {
                val cell = row + 1
                if (paths.overLimitLevel(indexField, cell) != null) continue
                if (!doc.filledAt(indexField, cell)) out += indexField to cell
            }
        }
        return out
    }

    /**
     * One `uniqueIndex` [Message] per cell of [dup] — the runtime twin of the kernel's auto index-field uniqueness
     * check (KERNEL-FINDINGS). The kernel flags **every** row sharing a duplicated value (not all-but-first); an
     * empty index value is excluded (it is a requiredness concern → [mandatoryErrors]). [duplicateIndexCells]
     * scopes the comparison per parent: a nested group's uniqueness is within one parent row (Parts within a
     * Line), not across all rows globally — the scope key is the index field's reps minus its own + the
     * group-row index ([List.dropLast] of 2).
     */
    fun uniquenessMessages(doc: Document, dup: Set<Pair<String, List<Int>>>, locale: String,
            isRelevant: Relevance): List<Message> =
        dup.filter { (path, reps) -> isRelevant(path, reps) }.map { (path, reps) ->
            formalMessage(UNIQUE_INDEX, uniqueRulePath(path), doc.messagePointer(path, reps), MsgType.VALUE,
                uniqueIndexText(locale))
        }

    /**
     * The target-owned diagnostic for an attempted computed value. This is the computation twin of
     * [formalErrors]: it deliberately runs only the BASIC target-format checks, because the Kernel does not
     * apply input-only charset/edge-blank checks to computed text. [genericWhenValid] covers the numeric
     * no-fit arm, which is errored even when its bounded attempted text has no more specific format error.
     */
    fun computedError(
        doc: Document,
        path: String,
        reps: List<Int>,
        raw: String,
        locale: String,
        genericWhenValid: Boolean = false,
    ): Message? {
        if (isCustomAt(path)) {
            val rejection = customTypeRejection(path, raw, locale) ?: return null
            return formalMessage(rejection.code, FORMAL_RULE_PATH, doc.messagePointer(path, reps),
                MsgType.VALUE, customMessage(rejection, path, locale))
        }
        val error = model.kinds[path]?.let { kind ->
            typeFormatErrorCached(
                kind, raw, model.scaleOf(path), model.dateLikeFormatOf(path), model.datePrecisionOf(path),
                model.rangeSeparatorOf(path), model.constraintsOf(path), model.baseYear ?: 2000, model.timeZone,
                model.rangeYearInterpretationOf(path), patterns::matches,
            )
        }
        if (error == null && !genericWhenValid) return null
        val pointer = doc.messagePointer(path, reps)
        return formalMessage(
            code = error?.id ?: COMPUTED_VALUE_ERROR,
            rulePath = FORMAL_RULE_PATH,
            pointer = pointer,
            type = MsgType.VALUE,
            text = error?.let { formatMessage(it, path, reps, raw, locale) }
                ?: computedValueErrorText(locale, messagePointerHouseForm(pointer)),
        )
    }

    /** Domain-failure diagnostic: a no-value computed target belongs to the formal-operand channel. */
    fun computedDomainError(doc: Document, path: String, reps: List<Int>, locale: String): Message {
        val pointer = doc.messagePointer(path, reps)
        return formalMessage(
            code = COMPUTED_VALUE_ERROR,
            rulePath = FORMAL_RULE_PATH,
            pointer = pointer,
            type = MsgType.VALUE,
            text = computedValueErrorText(locale, messagePointerHouseForm(pointer)),
        )
    }

    /**
     * Every formal message, built in one place because the kernel adds them all through one funnel
     * (`FormalChecker.addFormalError`, and `CalculationController.addBerechnungsFehler` for a computed value;
     * runtime classes): the offending field is its own referenced operand, and an omission names it as the
     * field whose filling clears the error. Locked across all seven formal codes by `FormalMessageReferenceDiffTest`.
     */
    private fun formalMessage(
        code: String,
        rulePath: String,
        pointer: A12PartiallyKnownMultiPointer,
        type: MsgType,
        text: String,
    ): Message = Message(code, rulePath, pointer, Severity.ERROR, type, text, listOf(pointer),
        if (type == MsgType.OMISSION) listOf(pointer) else emptyList())

    private fun mandatoryMessage(
        doc: Document,
        path: String,
        reps: List<Int>,
        locale: String,
        unsupported: MutableList<UnsupportedRule>,
    ): Message? {
        val ptr = doc.messagePointer(path, reps)
        val declared = model.fieldOf(path)?.requiredMessages.orEmpty()
        val text = if (declared.isEmpty()) {
            mandatoryFieldText(locale)
        } else {
            val template = declared[locale]
            if (template == null) {
                unsupported += UnsupportedRule(
                    messagePointerHouseForm(ptr),
                    "requiredness field-owned error template has no exact '$locale' declaration",
                    UnsupportedSubject.CELL,
                )
                return null
            }
            try {
                renderRequiredFieldMessage(template, locale, messageLabel(path, locale, reps))
            } catch (e: UnsupportedConstructException) {
                unsupported += UnsupportedRule(
                    messagePointerHouseForm(ptr),
                    e.message ?: "unsupported requiredness field-owned message",
                    UnsupportedSubject.CELL,
                )
                return null
            }
        }
        return formalMessage(MANDATORY_FIELD, mandatoryRulePath(path), ptr, MsgType.OMISSION, text)
    }

    private fun formatMessage(
        error: FormalErrorCode,
        path: String,
        reps: List<Int>,
        raw: String,
        locale: String,
    ): String {
        val declared = model.fieldOf(path)?.patternMessages.orEmpty()
        if (error != FormalErrorCode.PATTERN || declared.isEmpty()) {
            return formalErrorText(error, locale, model.scaleOf(path))
        }
        val template = declared[locale]
            ?: throw UnsupportedConstructException(
                "Invalid-value field-owned error template has no exact '$locale' declaration",
            )
        return renderPatternFieldMessage(template, model.conditionLanguage, messageLabel(path, locale, reps), raw)
    }

    /**
     * Whether the field at [path] is required-but-empty in [ctx] — the kernel's `mandatoryField` condition
     * AND the trigger that makes the field "unknown" for rule evaluation ([formalErrorAt]). Empty plus the
     * mode's gate: [Requiredness.ABSOLUTE] is unconditional with no repeatable ancestor, else gated by the
     * lowest repeatable ancestor being a live row; [Requiredness.RELATIVE_TO_PARENT] is gated by the
     * immediate parent being filled. Both gates ride [EvalContext.groupFilled] (repeatable = row exists,
     * non-repeatable = a descendant is filled).
     */
    private fun requiredEmpty(path: String, ctx: EvalContext, groupFilled: (EvalContext, String) -> Boolean): Boolean {
        if (ctx.filled(path)) return false
        return when (model.requirednessOf(path)) {
            Requiredness.NOT_REQUIRED -> false
            Requiredness.RELATIVE_TO_PARENT -> groupFilled(ctx, parentGroup(path))
            Requiredness.ABSOLUTE -> lowestRepeatableAncestor(path)?.let { groupFilled(ctx, it) } ?: true
        }
    }

    /**
     * Whether the per-cell over-repetition gate has to run at all for [doc] — the once-per-call precondition that
     * lets it be skipped wholesale (IG127.1).
     *
     * That gate ([overRepetitionResultAt]) is a `HashMap<String, PathInfo>` probe plus a bound walk, and
     * [ValueAdmissionCache.resultAt] must run it BEFORE consulting its memo, because an over-limit cell is exempt
     * from every value check. It depends on the coordinate, so it cannot ride in the value-shaped key without
     * reintroducing the list-in-key IF284 removed, and it is therefore unmemoized: emission, suppression,
     * `RepetitionNotUnique` and the computation poison gate each pay it again for the same cell. Measured at
     * **10.33 %** of a full validation. A per-PATH memo of any shape is the same probe (built, measured and
     * reverted; INTERPRETER-PERFORMANCE), so the lever that remains is not to ask per cell at all.
     *
     * This is the third member of a family the neighbouring code already guards the same way: `duplicates` and
     * `unavailable` are both coordinate-keyed sets that are empty in the ordinary case, and both are tested with
     * `isNotEmpty()` first, on the path every call takes. Over-limit was the member without the guard.
     *
     * **Why these two domains.** They mirror the two [overRepetitionMessages] walks — cells, then instantiated
     * rows — so "no gate needed" and "the emitter emits nothing" are one statement rather than an argument joining
     * two different domains. Each is deliberately a SUPERSET of the emitter's: [Document.placedAddresses] carries
     * present-but-EMPTY cells too (an address no valued placement holds, and exactly what the empty branch of
     * [computeFormalResultAt] consults), and the row scan covers every declared entity rather than only the BOUNDED
     * groups the emitter iterates. Scanning more addresses can only make a `false` answer stronger.
     *
     * **The name says "gate needed", not "an over-limit address exists", and the difference is load-bearing:** a
     * model whose declared maximum is below 1 returns `true` for an EMPTY document with no addresses at all. That
     * refusal is conservative on purpose — [mandatoryErrors] synthesises an all-1s address for an absolutely
     * required field that no placement need carry, and refusing outright is cheaper than reasoning about which
     * branch that address takes.
     *
     * **There is deliberately no `maximums.isEmpty()` early return.** It looks free and is not: both scans resolve
     * their path through the same `info`, whose assertion is the only thing that rejects an undeclared placement
     * once the gate is skipped, and returning before them silently drops it for any model that declares no bounds
     * — reachable through the public `ModelDef`, whose `groupPaths` defaults to empty. A cold review caught exactly
     * that regression here. When no bound is declared, `anyExceedsBound` still resolves each path and then returns
     * on its empty bound list, which is the cheap outcome without the lost assertion.
     *
     * A field address's verdict IS its containing group row's verdict: field paths carry no bound of their own
     * ([ModelDef.effectiveGroupRepetitionMaximums] excludes them), so every bound level of a field lies at an
     * ancestor group level and reads the same coordinates as that row. The row scan therefore already covers every
     * cell; the cell scan earns its place by carrying the `info` assertion for paths no row scan visits.
     */
    fun overRepetitionGateNeeded(doc: Document): Boolean {
        if (model.effectiveGroupRepetitionMaximums.values.any { it < 1 }) return true
        for ((path, addresses) in doc.placedAddresses()) {
            if (paths.anyExceedsBound(path, addresses.keys)) return true
        }
        for (entity in model.entityPaths) {
            val rows = doc.instantiatedRows(entity)
            if (rows.isNotEmpty() && paths.anyExceedsBound(entity, rows)) return true
        }
        return false
    }

    /**
     * The over-limit cell's result, or `null` when the cell is inside its declared repeatability.
     *
     * An over-limit cell (a group coordinate exceeds its effective maximum) is "unknown" — it carries the
     * over-repetition code, suppressing any rule that references it AND its own format/required/unique checks,
     * exactly as the kernel skips an over-limit instance's ordinary checks (KERNEL-FINDINGS "over-repetition").
     *
     * Extracted so it can be applied OUTSIDE the value-admission memo: it is the one part of a filled cell's
     * formal result that depends on the cell's COORDINATES rather than on its value, and keeping it out of the
     * memoized computation is what lets that memo key on `(path, raw)` instead of carrying the repetition list.
     */
    fun overRepetitionResultAt(path: String, reps: List<Int>): FormalResult.Invalid? =
        paths.exceededBound(path, reps)?.let { exceeded ->
            FormalResult.Invalid(FormalFailure.OverRepetition(overRepetitionType(exceeded).code))
        }

    /**
     * Whether [path] declares a **code-based** [CustomFieldType] — a consumer's own callback.
     *
     * The one thing in an admission that is not a pure function of the field and the value: its invocation count is
     * observable to the consumer, and the contract is one invocation per CELL (IF150/IF152). So
     * [ValueAdmissionCache] keeps the cell-shaped key for these fields and shares by value for every other, which
     * is what `CustomFieldTypeMultiplatformTest` measures by counting the calls a stateful validator sees. A
     * declarative [PredefinedType] and an UNREGISTERED custom type are both pure and need no exception.
     */
    fun isCustomAt(path: String): Boolean = model.customTypeOf(path) != null

    fun hasCodeBasedValidatorAt(path: String): Boolean =
        model.customTypeOf(path)?.let { it.name !in predefinedTypes && it.name in customFieldTypes } == true

    /**
     * The uncached value-owned admission result for one filled cell, before identity relations are built.
     *
     * A function of the FIELD and the VALUE only — except for the consumer callback [hasCodeBasedValidatorAt]
     * names, whose invocation count is part of the contract. The coordinate-dependent gate is
     * [overRepetitionResultAt], which [ValueAdmissionCache] applies before consulting this.
     */
    fun computeValueAdmissionAt(
        path: String,
        raw: String,
        locale: String,
        customInput: String,
    ): FormalResult {
        val kind = model.kinds[path] ?: return FormalResult.Valid
        val formatError = if (isCustomAt(path)) {
            io.github.mbackschat.a12.dm.interpreter.eval.baselineValueError(customInput, legalCharset)
        } else formalErrorCached(kind, raw, model.scaleOf(path), model.dateLikeFormatOf(path), model.datePrecisionOf(path),
            model.rangeSeparatorOf(path), model.constraintsOf(path), legalCharset, model.baseYear ?: 2000,
            model.timeZone, model.rangeYearInterpretationOf(path), patterns::matches)
        formatError?.let { return FormalResult.Invalid(FormalFailure.Format(it)) }
        return try {
            customTypeRejection(path, customInput, locale)?.let {
                if (it.code == CUSTOM_TEST_RANGE) FormalResult.Reported(it)
                else FormalResult.Invalid(FormalFailure.Custom(it))
            } ?: FormalResult.Valid
        } catch (e: UnsupportedConstructException) {
            FormalResult.Unsupported(e.message ?: "custom field type could not be evaluated")
        }
    }

    /** The uncached, complete formal/mandatory/duplicate-index result for one cell. */
    fun computeFormalResultAt(
        path: String,
        reps: List<Int>,
        raw: String?,
        ctx: EvalContext?,
        dup: Set<Pair<String, List<Int>>>,
        valueAdmissions: ValueAdmissionCache,
        groupFilled: (EvalContext, String) -> Boolean = { context, group -> context.groupFilled(group) },
    ): FormalResult {
        if (raw != null) {
            // The admission applies [overRepetitionResultAt] itself — it must precede every value check — so this
            // branch does not repeat the bound walk.
            val admission = valueAdmissions.resultAt(path, reps, raw)
            when (admission) {
                FormalResult.Valid -> Unit
                is FormalResult.Reported -> Unit
                is FormalResult.Invalid -> return admission
                is FormalResult.Unsupported -> return admission
            }
            // `isNotEmpty()` first, and the same guard rides every set keyed by `(path, reps)` here: `path to reps`
            // allocates a Pair and hashes the repetition list BEFORE an empty set can answer "no", and this set is
            // empty unless the document really does have a duplicated index value.
            return if (dup.isNotEmpty() && path to reps in dup) {
                FormalResult.Invalid(FormalFailure.Generated(UNIQUE_INDEX), (admission as? FormalResult.Reported)?.rejection)
            } else {
                admission
            }
        }
        // The EMPTY branch. Same document-level precondition as the filled branch's gate, read from the admission
        // cache so the call has exactly ONE answer to "can any address here be over-limit?" (IG127.1).
        if (valueAdmissions.overRepetitionGateNeeded) overRepetitionResultAt(path, reps)?.let { return it }
        return if (ctx != null && requiredEmpty(path, ctx, groupFilled)) FormalResult.Invalid(FormalFailure.Generated(MANDATORY_FIELD))
        else FormalResult.Valid
    }

    /** The project-specific rejection of the filled value [raw] at [path] by the field's declared custom field
     *  type, or null when the field is not custom-typed / the value is accepted / the type is unregistered. A
     *  declarative [PredefinedType] carries no project code, so its rejection uses the interpreter's own
     *  [CUSTOM_TYPE_INVALID]; a CODE-BASED [CustomFieldType] carries the validator's `getErrorKey()` (IF150). An
     *  UNregistered custom type returns null (the value is used leniently as a plain string and the cell is
     *  reported by [customTypeUnsupported] instead — the kernel throws without a validator; the interpreter
     *  degrades). A code-based check that can't run throws [UnsupportedConstructException] (JS worker down). */
    private fun customTypeRejection(path: String, raw: String, locale: String): CustomTypeRejection? {
        val declaration = model.customTypeOf(path) ?: return null
        predefinedTypes[declaration.name]?.let {
            return if (it.accepts(raw, patterns)) null else CustomTypeRejection(CUSTOM_TYPE_INVALID)
        }
        customFieldTypes[declaration.name]?.let {
            return it.check(
                raw,
                CustomFieldValidationContext(
                    locale,
                    declaration.minLength ?: DEFAULT_CUSTOM_MIN_LENGTH,
                    declaration.maxLength ?: DEFAULT_CUSTOM_MAX_LENGTH,
                ),
            )
        }
        return null                                                      // unregistered → unsupported, not rejected
    }

    private fun customMessage(rejection: CustomTypeRejection, path: String, locale: String): String =
        rejection.message
            ?.replace("\$<fieldName>\$", model.labelOf(path, locale))
            ?: customTypeInvalidText(locale)

    /** Filled cells whose declared custom field type has NO registered validator — reported [ValidationOutcome.unsupported]
     *  (the kernel throws "Unable to invoke validation" here; the interpreter degrades: it reports the cell and uses
     *  the value leniently as a plain string, so the rest of the document can still be validated / test-run). */
    fun customTypeUnsupported(doc: Document, isRelevant: Relevance): List<UnsupportedRule> =
        doc.valuedFields().filter { isRelevant(it.path, it.reps) }.mapNotNull { vf ->
            customTypeUnsupportedAt(vf.path, doc.formattedPointer(vf.path, vf.reps))
        }

    fun customTypeUnsupportedAt(path: String, pointer: String): UnsupportedRule? {
        val declaration = model.customTypeOf(path) ?: return null
        return if (declaration.name in predefinedTypes || declaration.name in customFieldTypes) null
            else UnsupportedRule(
                pointer,
                "custom field type '${declaration.name}' has no registered validator",
                UnsupportedSubject.CELL,
            )
    }

    /**
     * The STRUCTURAL over-repetition messages (KERNEL-FINDINGS "over-repetition errors"; the kernel's
     * `FormalChecker`): each entity instance whose group coordinate exceeds its effective maximum is
     * flagged according to the first exceeded coordinate's position: root → `zuGrosseLfdNummer`, deeper own
     * group coordinate → `zuGrosseZeile`, deeper ancestor → `zuGrosseKontextnummer` (KF58, SPEC-2026-09-08-01).
     * Both repeatable and fixed-cap groups follow this rule. Group display pointers omit their own trailing
     * index; message keys retain it. One VALUE message per over-limit instance. An
     * over-limit instance is "unknown": [computeFormalResultAt] suppresses rules over it and [formalErrors] skips
     * its format check (it carries the over-repetition code instead).
     */
    fun overRepetitionMessages(
        doc: Document,
        locale: String,
        isRelevant: Relevance,
        /** The call's [overRepetitionGateNeeded]. Both loops below compute [ModelPathIndex.exceededBound]
         *  BEFORE consulting relevance, so on an ordinary document this walk is two full scans that emit nothing.
         *  No default, for the reason [ValueAdmissionCache.overRepetitionGateNeeded] gives. */
        gateNeeded: Boolean,
    ): List<Message> {
        if (!gateNeeded || model.effectiveGroupRepetitionMaximums.isEmpty()) return emptyList()
        val out = mutableListOf<Message>()
        // Null/empty cells still own addresses rejected by the kernel (OverRepetitionOccurrenceDiffTest).
        for ((path, cells) in doc.placedAddresses()) {
            for (reps in cells.keys) {
                val exceeded = paths.exceededBound(path, reps) ?: continue
                if (!isRelevant(path, reps)) continue
                val type = overRepetitionType(exceeded)
                out += formalMessage(type.code, FORMAL_RULE_PATH, doc.messagePointer(path, reps), MsgType.VALUE,
                    type.messageText(locale))
            }
        }
        for (group in model.effectiveGroupRepetitionMaximums.keys) {
            val ownLevel = paths.levelOf(group)
            for (row in doc.instantiatedRows(group)) {
                val exceeded = paths.exceededBound(group, row) ?: continue
                if (!isRelevant(group, row)) continue
                val type = overRepetitionType(exceeded, ownLevel)
                out += formalMessage(type.code, FORMAL_RULE_PATH, doc.messagePointer(group, row), MsgType.VALUE,
                    type.messageText(locale))
            }
        }
        return out
    }

    private enum class OverRepetitionType(val code: String) {
        ROW(OVER_REPETITION_ROW),
        CONTEXT(OVER_REPETITION_CONTEXT),
        ROOT_SERIAL(OVER_REPETITION_FIXED),
    }

    private fun overRepetitionType(
        exceeded: ModelPathIndex.ExceededBound,
        ownLevel: Int? = null,
    ): OverRepetitionType = when (exceeded.level) {
        0 -> OverRepetitionType.ROOT_SERIAL
        ownLevel -> OverRepetitionType.ROW
        else -> OverRepetitionType.CONTEXT
    }

    private fun OverRepetitionType.messageText(locale: String): String = when (this) {
        OverRepetitionType.ROOT_SERIAL -> fixedRepetitionText(locale)
        OverRepetitionType.ROW -> overRepetitionText(locale, row = true)
        OverRepetitionType.CONTEXT -> overRepetitionText(locale, row = false)
    }

    /** The deepest repeatable ancestor group of [path] (the kernel's `lowestRepeatableGroupPath`), or null. */
    private fun lowestRepeatableAncestor(path: String): String? =
        ancestorGroups(path).filter { it in model.repeatable }.maxByOrNull { it.count { c -> c == '/' } }

    /** The iteration scope a `mandatoryField` is checked over: the deepest repeatable ancestor (per-row), else
     *  the field's always-instantiated root group (a single context). */
    private fun emissionScope(path: String): String = lowestRepeatableAncestor(path) ?: rootGroupOf(path)

    /** The kernel's autogenerated mandatory-rule path for [path] — `<parent>/vk_vk<field>_req`. */
    private fun mandatoryRulePath(path: String): String = "${parentGroup(path)}/vk_vk${pathParts(path).last()}_req"

    /** The autogenerated uniqueness-rule path for an index [path] — `<parent>/vk_vk<field>_unique`. */
    private fun uniqueRulePath(path: String): String = "${parentGroup(path)}/vk_vk${pathParts(path).last()}_unique"

    private companion object {
        /** Effective runtime bounds for an omitted CustomFieldType bound in both kernel strategies. */
        const val DEFAULT_CUSTOM_MIN_LENGTH = 1
        const val DEFAULT_CUSTOM_MAX_LENGTH = 999
    }
}
