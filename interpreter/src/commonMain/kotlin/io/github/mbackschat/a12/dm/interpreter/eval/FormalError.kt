/**
 * Formal-error detection — whether a raw field value is *well-formed for its kind*. The kernel runs this
 * BEFORE rule evaluation; a rule that references a formally-invalid field is **not evaluated** (the operand
 * is "unknown"), so the rule neither fires nor passes — it is *suppressed*. On a full validation the kernel
 * also EMITS a message per malformed field (rule path [FORMAL_RULE_PATH], severity ERROR, VALUE type).
 *
 * The closed set of checks is the [FormalErrorCode] enum; each carries the kernel's German internal
 * [FormalErrorCode.id] (KERNEL-FINDINGS §3 / "runtime formal-error codes"), surfaced verbatim so a consumer
 * sees the same `formalErrorCode` the kernel reports. An empty value is not malformed (emptiness is a
 * requiredness concern, not a format one).
 */

/** The kernel's sentinel rule path for a formal (format) check — distinct from any author rule's slash-path. */
const val FORMAL_RULE_PATH = "formalePruefung"

/**
 * The kernel's error code for a **required-but-empty** field (KERNEL-FINDINGS §4). Like a format error it
 * makes the field **"unknown"** for rule evaluation (the operand resolves to `Val.Unknown`, so the 3VL
 * propagates), but it is *not* a value-format check — it rides requiredness, so it lives outside the
 * [FormalErrorCode] enum. The kernel emits it from an autogenerated rule named `vk_vk<field>_req`.
 */
const val MANDATORY_FIELD = "mandatoryField"

/** Our OWN end-user text for the mandatory-field error (deliberately not the kernel's German bundle — the
 *  same Option-A choice as [formalErrorText], keeping the kernel-free artifact clear of kernel strings). */
fun mandatoryFieldText(locale: String): String =
    if (locale.startsWith("de")) "Pflichtfeld ist nicht ausgefüllt." else "A required field is not filled."

/**
 * The kernel's error code for a **duplicate index-field value** across repeatable rows (KERNEL-FINDINGS —
 * index-field uniqueness). The kernel auto-checks a repeatable group's `indexFieldName`: every row whose
 * (non-empty) index value duplicates another row's in the same parent scope is flagged. A VALUE error — you
 * fix it by changing a value, not by filling (an empty index is a requiredness concern → [MANDATORY_FIELD]).
 */
const val UNIQUE_INDEX = "uniqueIndex"

/** Our OWN end-user text for the duplicate-index error (Option-A, like [mandatoryFieldText]). */
fun uniqueIndexText(locale: String): String =
    if (locale.startsWith("de")) "Der Indexwert ist nicht eindeutig." else "The index value is not unique."

/**
 * The interpreter's INTERNAL marker for an eligible-but-UNSTAGED index-default cell in PARTIAL validation
 * (SPEC-2026-07-23-14): the kernel marks the cell invalid-for-validation WITHOUT any message
 * (`ValidationCache.addDefaultValuesForIndexFieldIfNecessary` → `markFieldAsInvalidForValidation`), so the
 * generated mandatory/uniqueness checks stay silent, dependent authored conditions read UNKNOWN, and the
 * containing group retains error state. This code never reaches an emitted [io.github.mbackschat.a12.dm.interpreter.model.Message]
 * — it only rides the formal-status channel (a `FormalFailure.Generated` that is neither [MANDATORY_FIELD]
 * nor [UNIQUE_INDEX]).
 */
const val INDEX_DEFAULT_SUPPRESSED = "indexDefaultSuppressed"

/**
 * The interpreter's code for a value REJECTED by its field's declared **custom field type** (`CustomFieldType` —
 * a client-SPI check, KERNEL-FINDINGS "Custom-extensibility surface"). Like a format error it makes the cell
 * **"unknown"** (a referencing rule is suppressed) and emits a per-cell message. The id is the interpreter's OWN
 * (Option-A, like [mandatoryFieldText]): the kernel emits the *validator's* project-specific error key, which is
 * not a fixed kernel code — so unlike the [FormalErrorCode] family there is no verbatim kernel id to carry.
 */
const val CUSTOM_TYPE_INVALID = "customFieldTypeInvalid"

/** Our OWN end-user text for a custom-field-type rejection (Option-A). */
fun customTypeInvalidText(locale: String): String =
    if (locale.startsWith("de")) "Wert ist kein gültiger Wert des benutzerdefinierten Feldtyps."
    else "Value is not a valid instance of the custom field type."

/**
 * The kernel's STRUCTURAL over-repetition codes (`FormalChecker.checkIndicesLessOrEqualThanMax`): a repeatable
 * group instance whose **own** row index exceeds its declared `repeatability` is **`zuGrosseZeile`** (on the
 * group entity); an entity (e.g. a field) sitting **inside** an over-limit repeatable ancestor — where the
 * over-limit index is an *intermediate* level, not the entity's own — is **`zuGrosseKontextnummer`**. A
 * non-repeatable group has effective maximum 1 and uses **`zuGrosseLfdNummer`** for itself and its descendants.
 * All are VALUE errors on the `formalePruefung` path, and an over-limit instance is "unknown" (its ordinary
 * checks are suppressed). KERNEL-FINDINGS §9. (The `FEHLER_LAUFENDE_NR_ZU_GROSS` sibling rides the
 * USB/multi-form form counter — out of the single-document interpreter's scope.)
 */
const val OVER_REPETITION_ROW = "zuGrosseZeile"
const val OVER_REPETITION_CONTEXT = "zuGrosseKontextnummer"
const val OVER_REPETITION_FIXED = "zuGrosseLfdNummer"

/** Our OWN end-user text for an over-repetition error (Option-A). */
fun overRepetitionText(locale: String, row: Boolean): String = when {
    row && locale.startsWith("de") -> "Es gibt mehr Zeilen, als die Wiederholbarkeit der Gruppe erlaubt."
    row -> "There are more rows than the group's repeatability allows."
    locale.startsWith("de") -> "Der Wiederholungsindex einer übergeordneten Gruppe ist zu groß."
