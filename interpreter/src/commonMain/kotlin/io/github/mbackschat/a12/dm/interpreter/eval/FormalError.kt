/*
 * Formal-error detection — whether a raw field value is *well-formed for its kind*. The kernel runs this
 * BEFORE rule evaluation; a rule that references a formally-invalid field is **not evaluated** (the operand
 * is "unknown"), so the rule neither fires nor passes — it is *suppressed*. On a full validation the kernel
 * also EMITS a message per malformed field (rule path [FORMAL_RULE_PATH], severity ERROR, VALUE type).
 *
 * The closed set of checks is the [FormalErrorCode] enum; each carries the kernel's German internal
 * [FormalErrorCode.id] (KERNEL-FINDINGS §3 / "runtime formal-error codes"), surfaced verbatim so a consumer
 * sees the same `formalErrorCode` the kernel reports. An empty value is not malformed (emptiness is a
 * requiredness concern, not a format one).
 */

/** The kernel's sentinel rule path for a formal (format) check — distinct from any author rule's slash-path. */
const val FORMAL_RULE_PATH = "formalePruefung"

/** The kernel's formal code for a numeric computation that produced no domain value, or for the numeric
 * no-fit store arm whose attempted text has no more specific target-format error. */
const val COMPUTED_VALUE_ERROR = "berechnungsWertFehler"

/** Kernel-free end-user wording for [COMPUTED_VALUE_ERROR]. */
fun computedValueErrorText(locale: String, pointer: String): String =
    if (locale.startsWith("de")) "Der berechnete Wert für $pointer ist ungültig."
    else "The computed value for $pointer is invalid."

/**
 * The kernel's error code for a **required-but-empty** field (KERNEL-FINDINGS §4). Like a format error it
 * makes the field **"unknown"** for rule evaluation (the operand resolves to `Val.Unknown`, so the 3VL
 * propagates), but it is *not* a value-format check — it rides requiredness, so it lives outside the
 * [FormalErrorCode] enum. The kernel emits it from an autogenerated rule named `vk_vk<field>_req`.
 */
const val MANDATORY_FIELD = "mandatoryField"

/** Our OWN end-user text for the mandatory-field error (deliberately not the kernel's German bundle — the
 *  same Option-A choice as [formalErrorText], keeping the kernel-free artifact clear of kernel strings). */
fun mandatoryFieldText(locale: String): String =
    if (locale.startsWith("de")) "Pflichtfeld ist nicht ausgefüllt." else "A required field is not filled."

/**
 * The kernel's error code for a **duplicate index-field value** across repeatable rows (KERNEL-FINDINGS —
 * index-field uniqueness). The kernel auto-checks a repeatable group's `indexFieldName`: every row whose
 * (non-empty) index value duplicates another row's in the same parent scope is flagged. A VALUE error — you
 * fix it by changing a value, not by filling (an empty index is a requiredness concern → [MANDATORY_FIELD]).
 */
const val UNIQUE_INDEX = "uniqueIndex"

/** Our OWN end-user text for the duplicate-index error (Option-A, like [mandatoryFieldText]). */
fun uniqueIndexText(locale: String): String =
    if (locale.startsWith("de")) "Der Indexwert ist nicht eindeutig." else "The index value is not unique."

/**
 * The interpreter's INTERNAL marker for an eligible-but-UNSTAGED index-default cell in PARTIAL validation
 * (SPEC-2026-07-23-14): the kernel marks the cell invalid-for-validation WITHOUT any message
 * (`ValidationCache.addDefaultValuesForIndexFieldIfNecessary` → `markFieldAsInvalidForValidation`), so the
 * generated mandatory/uniqueness checks stay silent, dependent authored conditions read UNKNOWN, and the
 * containing group retains error state. This code never reaches an emitted [io.github.mbackschat.a12.dm.interpreter.model.Message]
 * — it only rides the formal-status channel (a `FormalFailure.Generated` that is neither [MANDATORY_FIELD]
 * nor [UNIQUE_INDEX]).
 */
const val INDEX_DEFAULT_SUPPRESSED = "indexDefaultSuppressed"

/**
 * The interpreter's code for a value REJECTED by its field's declared **custom field type** (`CustomFieldType` —
 * a client-SPI check, KERNEL-FINDINGS "Custom-extensibility surface"). Like a format error it makes the cell
 * **"unknown"** (a referencing rule is suppressed) and emits a per-cell message. The id is the interpreter's OWN
 * (Option-A, like [mandatoryFieldText]): the kernel emits the *validator's* project-specific error key, which is
 * not a fixed kernel code — so unlike the [FormalErrorCode] family there is no verbatim kernel id to carry.
 */
const val CUSTOM_TYPE_INVALID = "customFieldTypeInvalid"

/** Our OWN end-user text for a custom-field-type rejection (Option-A). */
fun customTypeInvalidText(locale: String): String =
    if (locale.startsWith("de")) "Wert ist kein gültiger Wert des benutzerdefinierten Feldtyps."
    else "Value is not a valid instance of the custom field type."

/**
 * The kernel's STRUCTURAL over-repetition codes are selected by the first exceeded coordinate's position:
 * position zero is **`zuGrosseLfdNummer`**, a deeper group's own coordinate is **`zuGrosseZeile`**, and a
 * deeper ancestor coordinate is **`zuGrosseKontextnummer`**. Repeatability determines the cap, not the code
 * (KF58, corrected by RootOverLimitPositionDiffTest, 2026-09-08).
 * All are VALUE errors on the `formalePruefung` path, and an over-limit instance is "unknown" (its ordinary
 * checks are suppressed). KERNEL-FINDINGS §9. (The `FEHLER_LAUFENDE_NR_ZU_GROSS` sibling rides the
 * USB/multi-form form counter — out of the single-document interpreter's scope.)
 */
const val OVER_REPETITION_ROW = "zuGrosseZeile"
const val OVER_REPETITION_CONTEXT = "zuGrosseKontextnummer"
const val OVER_REPETITION_FIXED = "zuGrosseLfdNummer"

/** Our OWN end-user text for an over-repetition error (Option-A). */
fun overRepetitionText(locale: String, row: Boolean): String = when {
    row && locale.startsWith("de") -> "Es gibt mehr Zeilen, als die Wiederholbarkeit der Gruppe erlaubt."
    row -> "There are more rows than the group's repeatability allows."
    locale.startsWith("de") -> "Der Wiederholungsindex einer übergeordneten Gruppe ist zu groß."
    else -> "A containing group's repetition index is too large."
}

/** Our own root-coordinate error text; the function name is retained for source compatibility. */
fun fixedRepetitionText(locale: String): String =
    if (locale.startsWith("de")) "Der Wiederholungsindex der Wurzelgruppe überschreitet ihre Obergrenze."
    else "The root group's repetition index exceeds its maximum."

/**
 * The formal-error checks the interpreter performs, each with the kernel's verbatim [id].
 *
 * **One code per ABSTRACT ERROR, never one per message-bundle key** — the constant is our own check, the [id]
 * is what a consumer reads, and the two are deliberately not one-to-one: several constants share an [id] where
 * the kernel surfaces one code for several of its own texts (`datumFalsch` carries three of ours,
 * `zahlFalscheAnzahlNachkommastellen` and `datumBereichDatumFalsch` two each). The kernel's emitter has the
 * same two axes — `FehlerHandler.addFehler(errorKey, fehlerText, param)` takes the surfaced code and the
 * resolved text separately, and its 44 Number bundle keys under `ZAHL_`/`GBMC_`/`GBOC_` sit behind 14 codes —
 * so an implementation that mirrored the bundle keys would report codes no consumer can match. Nothing here
 * reads a number's art or any other text-selection axis. Asked by a12-kernel-lean's `SPEC-2026-09-07-13`;
 * every formal-error differential in `adapter/…/laws` is what holds it, by comparing this [id] against the
 * kernel's own on each row.
 */
enum class FormalErrorCode(val id: String) {
    /** A DATE value that is not `YYYY-MM-DD`. */
    DATE_FORMAT("datumFormatFalsch"),

    /** A lexically well-shaped partial Date whose zero components do not form the required day→month→year
     *  suffix. The kernel uses the same `datumFalsch` id as its concrete-date validity failure. */
    PARTIAL_DATE_INVALID("datumFalsch"),

    /** A well-formed DATE value that resolves to a real calendar date but is BEFORE the kernel's always-on
     *  floor `Constants.DATE_FROM = 1583-10-16` (the start of the Gregorian calendar). The kernel flags it
     *  `datumFalsch` (FEHLER_DATUM) for every stored OR computed date, independent of the opt-in "< 1900"
     *  additional check — confirmed in both strategies (IF88). */
    DATE_TOO_EARLY("datumFalsch"),

    /** A DATE / DATEFRAGMENT value before 1900-01-01 on a declaration carrying the **opt-in** additional check
     *  (`youngerThan1900Check`). The kernel surfaces the same `datumFalsch` code as the always-on floor but
     *  selects a different message key for it (`DATUM_ADDITIONAL_CHECK` beside `DATUM`), so this is a second
     *  TEXT behind one code — the same shape as [PARTIAL_DATE_INVALID]. Its declaration is gated:
     *  `MVK_ADDITIONAL_CHECK_INVALID` refuses the check unless the declared format carries a year (KF251), so a
     *  year-free DATE or DATEFRAGMENT cannot reach this class at all. */
    DATE_BEFORE_1900("datumFalsch"),

    /** ANY stored value longer than the kernel's fixed technical limit of [TECHNICAL_VALUE_LIMIT] UTF-16 code
     *  units, measured on the AUTHORED text before CRLF normalization — the kernel's `wertZuLang`
     *  (`FormalChecker.checkFieldValueTooLong`). It is the first input gate, ahead of the charset and blank
     *  checks, for every kind except a raw `noValueValidation` String, and it is distinct from a declared
     *  `maxLength` ([STRING_TOO_LONG]). A computed value never meets it (KERNEL-FINDINGS KF547). */
    VALUE_TOO_LONG("wertZuLang"),

    /** A stored value with a **leading** blank — a baseline value check the kernel runs before the type format
     *  (`checkFieldValueFormat`), for every kind (string/number/date/…) except a raw `noValueValidation` String,
     *  and after [VALUE_TOO_LONG]. IF43. */
    LEADING_BLANK("fuehrendesBlank"),

    /** A stored value with a **trailing** blank — the baseline-check sibling of [LEADING_BLANK], with its exception
     *  and right after it (IF43, KF547). */
    TRAILING_BLANK("nachfolgendesBlank"),

    /** A stored value (not a raw `noValueValidation` String) containing a character outside the model's legal
     *  charset, checked on the authored text before CRLF normalization. With no programming-language
     *  charset configured (a DM-JSON model), the default legal set is the **BMP** (`0x0000-0xFFFF`), so any
     *  SUPPLEMENTARY-plane character (a UTF-16 surrogate pair, e.g. an emoji) is illegal. IF43. */
    CHARSET("ZeichenNichtImZeichensatz"),

    /** A NUMBER value with non-numeric characters. */
    INVALID_NUMBER("zahlHatUngueltigeZeichen"),

    /** A decimal separator in a scale-0 (integer) NUMBER field. */
    DECIMAL_SEPARATOR("zahlHatDezimalTrenner"),

    /** More fractional digits than the NUMBER field's scale allows. */
    TOO_MANY_DECIMALS("zahlFalscheAnzahlNachkommastellen"),

    /** A NUMBER zero carrying a minus sign (`-0`, `-0.00`) on a field that is **signed and permits zero** — the
     *  kernel's signed-zero check conjoins `nullErlaubt && hatVorzeichen`, so this class is DISJOINT from
     *  [SIGN_ON_UNSIGNED] and from [ZERO_NOT_ALLOWED] rather than preceding either (KF253). */
    SIGNED_ZERO("zahlNullEnthaeltVorzeichen"),

    /** A minus sign on an **unsigned** NUMBER field (`NumberType.positivesOnly`, the kernel's
     *  `hatVorzeichen == false`). Any minus fires it, zero magnitude included; the one exception is a
     *  zero-magnitude value on an unsigned, zero-forbidding **money** field, which the kernel reports as
     *  [ZERO_NOT_ALLOWED] instead (KF253). */
    SIGN_ON_UNSIGNED("zahlMitVorzeichen"),

    /** A NUMBER with a leading plus sign (`+5`, `+0`) — the kernel forbids an explicit plus. */
    PLUS_SIGN("zahlMitPlus"),

    /** A DATE_RANGE value that does not CONTAIN its declared separator. Containment is the whole test: once
     *  the separator is present, a bad split shape is [DATE_RANGE_FORMAT], not this. */
    DATE_RANGE_SEPARATOR("datumBereichTrennerFehlt"),

    /** A DATE_RANGE value that contains its separator but is still not two dates — the split is not exactly two
     *  parts, an endpoint is empty, or a side is not a valid date for the field's format. */
    DATE_RANGE_FORMAT("datumBereichFormatFalsch"),

    /** A DATE_RANGE with two valid dates, but the start is AFTER the end (start == end is allowed). */
    DATE_RANGE_INVALID("datumBereichNichtGueltig"),

    /** A DATE_RANGE whose START date is before the Gregorian-calendar floor (1583-10-16) — the range sibling
     *  of [DATE_TOO_EARLY] (`FormatDefinitionDatumBereich extends FormatDefinitionDatum`; the kernel floors the
     *  start, and end >= start covers the end). Kernel code `datumBereichDatumFalsch` (FEHLER_DATUM_BEREICH_DATUM). */
    DATE_RANGE_TOO_EARLY("datumBereichDatumFalsch"),

    /** A DATE_RANGE whose START is before 1900-01-01 on a declaration carrying the **opt-in** additional check
     *  (`DateRangeType.youngerThan1900Check`) — the range sibling of [DATE_BEFORE_1900], sharing
     *  `datumBereichDatumFalsch` with the always-on floor. Unlike the DATE and DATEFRAGMENT kinds, the kernel
     *  admits the check on a **year-free** range format, where it then reads the base-year completion (KF253). */
    DATE_RANGE_BEFORE_1900("datumBereichDatumFalsch"),

    // ── Declared field-type CONSTRAINT violations (IF20) — auto-fired against the field-type declaration,
    //    same `formalePruefung` mechanism as the format checks above (KERNEL-FINDINGS §3 "declared field-type
    //    constraints"). Each carries the kernel's verbatim runtime code; all are VALUE errors. ──
    /** A STRING shorter than the field's declared `minLength` (the kernel's `stringZuKurz`). */
    STRING_TOO_SHORT("stringZuKurz"),

    /** A STRING longer than the field's declared `maxLength` (the kernel's `stringZuLang`). */
    STRING_TOO_LONG("stringZuLang"),

    /** A STRING not matching the field's declared `pattern`, OR an ENUM value not in the field's value domain
     *  (both → the kernel's `stringFalschesMuster`; the pattern/domain check runs BEFORE the length checks). */
    PATTERN("stringFalschesMuster"),

    /** A NUMBER below the field's declared `minValue` (the kernel's `zahlZuKlein`). */
    NUMBER_TOO_SMALL("zahlZuKlein"),

    /** A NUMBER above the field's declared `maxValue` (the kernel's `zahlZuGross`). */
    NUMBER_TOO_BIG("zahlZuGross"),

    /** A NUMBER with a decimal point but FEWER fractional digits than `minFractionalDigits` — the kernel's
     *  `zahlFalscheAnzahlNachkommastellen` (the SAME code as [TOO_MANY_DECIMALS]; "wrong number of decimals"). */
    TOO_FEW_DECIMALS("zahlFalscheAnzahlNachkommastellen"),

    /** A NUMBER with NO decimal point where `minFractionalDigits > 0` requires one (the kernel's
     *  `zahlOhneDezimalTrenner` — "number without decimal separator"). */
    NO_DECIMAL_SEPARATOR("zahlOhneDezimalTrenner"),

    /** A STRING containing a line break where the field does not permit them (the kernel's `stringMitNewline`).
     *  **Default-forbidden** — fires unless the field declares `lineBreaksPermitted: true` (an ENUM never can —
     *  its kernel format definition hard-codes `lineBreakAllowed = false`). Checked as a format concern, the
     *  FIRST value clause — before enum-domain, pattern, and the length checks (differentially pinned, IF124). */
    NEWLINE("stringMitNewline"),

    /** A NUMBER whose integer part carries a forbidden leading zero (`07`, `00`, `00.50`; the kernel's
     *  `zahlHatFuehrendeNullen`). **Default-forbidden** — fires unless the field declares `leadingZerosAllowed:
     *  true`. A lone `0` and `0.50` (integer part `0`) are fine. */
    LEADING_ZEROS("zahlHatFuehrendeNullen"),

    /** A NUMBER equal to zero where the field declares `zeroNotAllowed: true` (the kernel's `zahlIstNull`). */
    ZERO_NOT_ALLOWED("zahlIstNull"),

    /** A NUMBER whose INTEGER-part digit count exceeds the field's integer-digit cap — the kernel's
     *  `zahlZuvieleVorkommastellen`. The cap is the explicit `maxIntegerDigits`, or (when unset) a `trait:"amount"`
     *  field's implicit `15 − maxFractionalDigits`: the kernel's `TypeConverter` maps BOTH to the one
     *  `maxDigitsBeforeDecimalPlace` cap firing the one code (amount is not a separate code). Sign and fractional
     *  digits are excluded from the count; checked AFTER the [TOTAL_DIGITS_TOO_LONG] parse check. */
    TOO_MANY_INTEGER_DIGITS("zahlZuvieleVorkommastellen"),

    /** A NUMBER with MORE THAN 15 TOTAL digits (integer + fractional, sign and decimal separator excluded) — the
     *  kernel's `stelligkeitZuLang`. This is a GENERIC parse-time sanity check on EVERY number (the kernel's
     *  `FormatDefinitionZahl.validiereFormat` / `NumberConversion.sanityCheck`), NOT a `trait:"amount"` concern:
     *  it fires right after the invalid-character check and BEFORE the sign / scale / leading-zero / integer-cap
     *  checks (probe-verified it beats leading-zeros, the decimal-separator check, and signed-zero). */
    TOTAL_DIGITS_TOO_LONG("stelligkeitZuLang"),

    /** A NUMBER whose value-string length is below the field's declared `minLength` (the kernel's `zahlZuKurz`);
     *  the length counts the full stored text incl. sign and decimal point. */
    NUMBER_TOO_SHORT("zahlZuKurz"),

    /** A NUMBER whose value-string length exceeds the field's declared `maxLength` (the kernel's `zahlZuLang`). */
    NUMBER_TOO_LONG("zahlZuLang"),

    /** A BOOLEAN token other than the exact lowercase `true` / `false` — the kernel's `feldJaNeinFalsch`. The
     *  check is **case-SENSITIVE**: `TRUE`, `FALSE`, and `True` are all formally invalid, as are `yes`/`1`/`0`.
     *  (Distinct from the *evaluation* of an already-stored value, which reads case-insensitively; and from JSON
     *  ingress, which normalizes `"TRUE"` to `true` before storage, exactly as A12's converter does — so this
     *  fires on the internal path where a caller fills a `Document` directly. Probe-measured, IF229.) */
    BOOLEAN_INVALID("feldJaNeinFalsch"),

    /** A CONFIRM token other than the exact lowercase `true` — the kernel's `feldJaFalsch`. A confirm has no
     *  false: a well-formed `false` is a formal error, as are `TRUE`, `yes`, and `1` (probe-measured, IF229). */
    CONFIRM_INVALID("feldJaFalsch"),
}

fun formalError(
    kind: Kind, raw: String, scale: Int? = null, format: String? = null,
    datePrecision: DatePrecision = DatePrecision.FULL, rangeSep: String? = null,
    constraints: FieldConstraints = FieldConstraints.NONE,
    legalCharset: LegalCharset = LegalCharset.BMP,
    /** The model's base year (kernel default 2000) — the year a year-less date FRAGMENT (`MM`, `MM-dd`)
     *  completes to for its realness check; unused for non-fragment kinds. */
    baseYear: Int = 2000,
    /** The model's configured time zone — a Europe/Berlin DATE_TIME inside the spring-forward gap is
     *  `datumFormatFalsch` (the kernel's non-lenient zone-set parse rejects it; KERNEL-FINDINGS §6). */
    timeZone: ModelTimeZone = ModelTimeZone.UTC,
    /** A DATE_RANGE field's `interpretationOfYear` — a WRAPPING yearless value such as `01.11-31.01` is
     *  ordered under [RangeYearInterpretation.FROM]/[RangeYearInterpretation.TO] and unordered without one. */
    rangeYearInterpretation: RangeYearInterpretation = RangeYearInterpretation.STANDARD,
    /** The stored text before CRLF normalization, which the input gates measure; [raw] is its evaluation form. */
    authored: String = raw,
): FormalErrorCode? {
    return formalErrorCached(
        kind, raw, scale, format, datePrecision, rangeSep, constraints, legalCharset, baseYear, timeZone,
        rangeYearInterpretation, authored,
    ) { pattern, value -> compilePattern(pattern).matches(value) }
}

internal fun formalErrorCached(
    kind: Kind, raw: String, scale: Int? = null, format: String? = null,
    datePrecision: DatePrecision = DatePrecision.FULL, rangeSep: String? = null,
    constraints: FieldConstraints = FieldConstraints.NONE,
    legalCharset: LegalCharset = LegalCharset.BMP,
    baseYear: Int = 2000,
    timeZone: ModelTimeZone = ModelTimeZone.UTC,
    /** A DATE_RANGE field's `interpretationOfYear` — a WRAPPING yearless value such as `01.11-31.01` is
     *  ordered under [RangeYearInterpretation.FROM]/[RangeYearInterpretation.TO] and unordered without one. */
    rangeYearInterpretation: RangeYearInterpretation = RangeYearInterpretation.STANDARD,
    authored: String = raw,
    patternMatches: (String, String) -> Boolean,
): FormalErrorCode? {
    if (raw.isEmpty()) return null
    // A raw `noValueValidation` String is never checked at all — the kernel returns before its technical length
    // guard and its baseline (`FormalChecker.checkAndConvertFieldValue`, KF547).
    if (constraints.noValueValidation) return null
    // The INPUT gates the kernel runs for EVERY other kind before the type format, on the authored text: the
    // technical length guard, then the baseline (IF43) — legal charset (default BMP; [legalCharset] customizes
    // it, e.g. DIN 91379), leading blank, trailing blank. They pre-empt the type-specific check (a ` 2024-01-01`
    // DATE is `fuehrendesBlank`).
    inputGateError(authored, legalCharset)?.let { return it }
    return typeFormatErrorCached(
        kind, raw, scale, format, datePrecision, rangeSep, constraints, baseYear, timeZone,
        rangeYearInterpretation, patternMatches,
    )
}

/**
 * The TYPE-format half of [formalError] alone — the kernel's `checkFieldValueFormatBasic` (only
 * `IFormatDefinition.validiereFormat`, no baseline checks). This is the check a COMPUTED value gets
 * (`CalculationController.checkField` inside every `handleBerechnetenWert` overload): a computed result may
 * legally start/end with a blank or carry any charset — only its type format and declared constraints decide
 * "fehlerhaft berechnet" (`FieldValueAsStringComputeDiffTest`). Stored INPUT values take [formalError] (the
 * kernel's full `checkFieldValueFormat` = charset → leading blank → trailing blank → this).
 */
fun typeFormatError(
    kind: Kind, raw: String, scale: Int? = null, format: String? = null,
    datePrecision: DatePrecision = DatePrecision.FULL, rangeSep: String? = null,
    constraints: FieldConstraints = FieldConstraints.NONE,
    baseYear: Int = 2000,
    timeZone: ModelTimeZone = ModelTimeZone.UTC,
    /** A DATE_RANGE field's `interpretationOfYear` — a WRAPPING yearless value such as `01.11-31.01` is
     *  ordered under [RangeYearInterpretation.FROM]/[RangeYearInterpretation.TO] and unordered without one. */
    rangeYearInterpretation: RangeYearInterpretation = RangeYearInterpretation.STANDARD,
): FormalErrorCode? {
    return typeFormatErrorCached(
        kind, raw, scale, format, datePrecision, rangeSep, constraints, baseYear, timeZone,
        rangeYearInterpretation,
    ) { pattern, value -> compilePattern(pattern).matches(value) }
}

internal fun typeFormatErrorCached(
    kind: Kind, raw: String, scale: Int? = null, format: String? = null,
    datePrecision: DatePrecision = DatePrecision.FULL, rangeSep: String? = null,
    constraints: FieldConstraints = FieldConstraints.NONE,
    baseYear: Int = 2000,
    timeZone: ModelTimeZone = ModelTimeZone.UTC,
    /** A DATE_RANGE field's `interpretationOfYear` — a WRAPPING yearless value such as `01.11-31.01` is
     *  ordered under [RangeYearInterpretation.FROM]/[RangeYearInterpretation.TO] and unordered without one. */
    rangeYearInterpretation: RangeYearInterpretation = RangeYearInterpretation.STANDARD,
    patternMatches: (String, String) -> Boolean,
): FormalErrorCode? {
    if (raw.isEmpty()) return null
    return when (temporalClassifier(kind, format)) {
        // Format-aware: a value valid for the field's DECLARED format is well-formed (a `dd.MM.yyyy` field's
        // `15.06.2024` is fine — not ISO, but valid for its format). Null format defaults to ISO (KERNEL-FINDINGS
        // plain-date locale handling, PlainDateDiffTest). Precision widens what "valid" means: partial DateType
        // omissions form the day→month→year suffix; a FRAGMENT is well-formed iff its value parses in its
        // (partial) format with real components (`completeFragmentToIso`) — a `2024-13` yyyy-MM is malformed.
        Kind.DATE -> {
            val fmt = format ?: ISO_FORMAT
            val invalidPartialShape = when (datePrecision) {
                DatePrecision.DAY_OPTIONAL,
                DatePrecision.MONTH_OPTIONAL,
                DatePrecision.YEAR_OPTIONAL,
                -> invalidPartialDateOmissionShape(raw, fmt, datePrecision)
                DatePrecision.FULL, DatePrecision.FRAGMENT -> false
            }
            // The formal check temporarily replaces every admitted unknown component with 2000/01/01 before
            // the ordinary date checks. Evaluation never receives that synthetic year.
            val parts = when (datePrecision) {
                DatePrecision.DAY_OPTIONAL,
                DatePrecision.MONTH_OPTIONAL,
                DatePrecision.YEAR_OPTIONAL,
                -> partialDateParts(raw, fmt, datePrecision)?.let { (y, m, d) ->
                    Triple(if (y == 0) 2000 else y, if (m == 0) 1 else m, if (d == 0) 1 else d)
                }
                // Formal completion appends the Base Year only to a day-and-month format; any other omitted year
                // takes the parser's default, so a month-only value escapes the floor (formalCompletionYear).
                DatePrecision.FRAGMENT ->
                    completeFragmentToIso(raw, fmt, formalCompletionYear(fmt, baseYear) ?: baseYear)?.let { dateParts(it) }
                DatePrecision.FULL -> {
                    // A DateType's declared format may itself OMIT calendar components — `yyyy`, `yyyy-MM`,
                    // `yyyyMM` and `MM` are all kernel-legal (KF176) — and such a value is complete FOR ITS
                    // FORMAT, so it is well-formed and the kernel completes the rest exactly as it completes a
                    // DateFragmentType. Parse the complete form first, then fall back to the shared fragment
                    // completion; this is already how a DATE_RANGE endpoint is checked below. This used to admit
                    // only the exact `yyyy` case (added for SPEC-2026-07-27-13's Date(...) year-component
                    // source, with a comment declining to infer the others) — so `yyyy-MM`, `yyyyMM` and `MM`
                    // drew a FALSE datumFormatFalsch on a legal model (IG110).
                    val iso = parseDateToIso(raw, fmt)
                        ?: completeFragmentToIso(raw, fmt, formalCompletionYear(fmt, baseYear) ?: baseYear)
                    iso?.let { dateParts(it) }
                }
            }
            when {
                invalidPartialShape -> FormalErrorCode.PARTIAL_DATE_INVALID
                parts == null -> FormalErrorCode.DATE_FORMAT
                // Year ZERO is an unreal component, not a date below the floor — reality is settled before
                // position in time (KF207's ordering), so `0000` is `datumFormatFalsch` while `0001` is
                // `datumFalsch`. Measured uniform across every date-bearing format and all three kinds; we
                // reported the floor for it, which is the right polarity under the wrong code. A partial
                // precision cannot reach here with a zero year: an omitted component is substituted above.
                parts.first == 0 -> FormalErrorCode.DATE_FORMAT
                // The kernel's always-on Gregorian floor (IF88): a real date before 1583-10-16 is `datumFalsch`.
                beforeGregorianStart(parts.first, parts.second, parts.third) -> FormalErrorCode.DATE_TOO_EARLY
                // The field-owned additional check runs after partial-date completion and the ordinary floor.
                constraints.rejectBefore1900 && parts.first < 1900 -> FormalErrorCode.DATE_BEFORE_1900
                else -> null
            }
        }
        // Format well-formedness FIRST (blanks, invalid chars, signed-zero/plus, decimal-separator,
        // too-MANY decimals via scale); only a well-formed number reaches the declared-constraint checks
        // (min fractional digits, then range) — KERNEL-FINDINGS §3 precedence.
        Kind.NUMBER -> numberFormalError(raw, scale, constraints) ?: numberConstraintError(raw, constraints)
        // A malformed TIME / DATE_TIME value carries the kernel's `datumFormatFalsch` (probe-verified — the same
        // code as DATE), and resolving it to Val.Unknown suppresses a referencing rule. (TIME was previously
        // unchecked entirely, so a malformed time even *escaped* suppression — KERNEL-FINDINGS §6 / IF8.)
        Kind.TIME -> if (parseTimeToIso(raw, format ?: "HH:mm:ss") != null) null else FormalErrorCode.DATE_FORMAT
        Kind.DATE_TIME -> {
            // Both of the kind's legal declared formats, via the shared canonicalization — a time-only
            // `HH:mm:ss` DATE_TIME is legal and used to be reported malformed here (IF301).
            val canonical = parseDeclaredDateTime(raw, format ?: "yyyy-MM-dd'T'HH:mm:ss")
            when {
                canonical == null -> FormalErrorCode.DATE_FORMAT
                // A Europe/Berlin wall time inside the spring-forward gap does not exist — the kernel's
                // non-lenient zone-set parse rejects it with the SAME code (probe-verified, KERNEL-FINDINGS §6).
                // Only a date-bearing value can sit in a gap: a time-only cell names no calendar day, so there
                // is no transition to fall into, and the guard must not be applied to its `HH:mm:ss` canonical.
                isIsoDateTime(canonical) && isGapLocal(canonical, timeZone) -> FormalErrorCode.DATE_FORMAT
                // A DateTime carries the SAME always-on Gregorian floor as a Date (KF207): the kernel has no
                // DateTime-specific formal code and reports through the Date pair, so a date-bearing instant
                // before 1583-10-16 is `datumFalsch`, not merely malformed. Only a date-bearing value can be
                // below the floor — a time-only `HH:mm:ss` canonical names no calendar day. Year ZERO is the
                // unreal-component case and takes the format code instead, on the same measured ordering as the
                // date classifier above.
                isIsoDateTime(canonical) && canonical.startsWith("0000-") -> FormalErrorCode.DATE_FORMAT
                isIsoDateTime(canonical) && dateParts(canonical.substring(0, 10))
                    ?.let { (y, m, d) -> beforeGregorianStart(y, m, d) } == true ->
                    FormalErrorCode.DATE_TOO_EARLY
                else -> null
            }
        }
        // A malformed DATE_RANGE carries one of the kernel's `datumBereich*` codes (probe-verified). The split
        // is TWO checks, not one, and the kernel decides them in this order (`FormatDefinitionDatumBereich`):
        // a value that does not CONTAIN the declared separator → `datumBereichTrennerFehlt`; a value that does
        // contain it but whose split is not exactly two NON-EMPTY parts → `datumBereichFormatFalsch` — the
        // kernel's `splitStringBySeparator` preserves empty tokens, so an extra separator and either empty
        // endpoint are SHAPE errors, not a missing separator (SPEC-2026-08-18-01, `DateRangeSplitFormalTest`).
        // The two empty-endpoint conjuncts carry the kernel's ORDER, not an observable outcome: an empty side
        // fails `parseDateToIso`/`completeFragmentToIso` one branch later and reaches the same code anyway, so
        // deleting them changes nothing a test can see (mutation-checked, 2026-08-19). They stay because the
        // owner decides shape before parsing and a future endpoint parser that accepted "" would diverge
        // silently without them — but no row here discriminates them, and only the extra-separator case does.
        // Then, on a well-shaped split: a side that is not a valid date for the format (incl. calendar-invalid
        // like 31.02) → `datumBereichFormatFalsch`; two valid dates but start AFTER end →
        // `datumBereichNichtGueltig` (start == end is allowed). A malformed range also resolves to Val.Unknown,
        // suppressing a referencing rule. Each side parses BY THE DECLARED format, whatever its granularity —
        // a FRAGMENT format (a `yyyy` year-range like `2024/2025`, a real workspace idiom) completes to its
        // earliest concrete date exactly like a fragment DATE field (`FragmentRangeFormalDiffTest`).
        Kind.DATE_RANGE -> {
            if (format == null || rangeSep == null) null   // no range config → nothing to check
            else {
                val parts = splitDateRange(raw, rangeSep)
                when {
                    parts.size == 1 -> FormalErrorCode.DATE_RANGE_SEPARATOR
                    parts.size != 2 || parts[0].isEmpty() || parts[1].isEmpty() ->
                        FormalErrorCode.DATE_RANGE_FORMAT
                    else -> {
                        // The ORDER check must see the endpoints EVALUATION sees. A wrapping yearless range is
                        // ordered once `interpretationOfYear` has moved one endpoint's year, so comparing two
                        // base-year completions would report the kernel's ordinary winter season unordered.
                        val shifted = parseRangeToIso(raw, format, rangeSep, baseYear, rangeYearInterpretation)
                        val a = shifted?.first
                            ?: parseDateToIso(parts[0], format) ?: completeFragmentToIso(parts[0], format, baseYear)
                        val b = shifted?.second
                            ?: parseDateToIso(parts[1], format) ?: completeFragmentToIso(parts[1], format, baseYear)
                        // BOTH date-position checks read the year the KERNEL's completion gives the start,
                        // which on a year-free format is not always the one the endpoint was built with —
                        // formalCompletionYear carries that rule and its measured basis.
                        val startParts = a?.let { dateParts(it) }
                        val positionYear = startParts?.let {
                            formalCompletionYear(format, baseYear) ?: it.first
                        }
                        when {
                            a == null || b == null || startParts == null || positionYear == null ->
                                FormalErrorCode.DATE_RANGE_FORMAT
                            a > b -> FormalErrorCode.DATE_RANGE_INVALID   // ISO strings: lexicographic == chronological
                            // The kernel floors the range START at 1583-10-16 (IF88); end >= start covers the end.
                            beforeGregorianStart(positionYear, startParts.second, startParts.third) ->
                                FormalErrorCode.DATE_RANGE_TOO_EARLY
                            // The range's OWN opt-in additional check (`DateRangeType.youngerThan1900Check`),
                            // on the START date. Unlike DATE/DATEFRAGMENT, the kernel does not statically
                            // refuse the flag on a year-free range format, so this clause is reachable (KF253).
                            // Same code as the floor, because the kernel's two arms share
                            // FEHLER_DATUM_BEREICH_DATUM.
                            constraints.rejectBefore1900 && positionYear < 1900 ->
                                FormalErrorCode.DATE_RANGE_BEFORE_1900
                            else -> null
                        }
                    }
                }
            }
        }
        // A STRING (incl. an ENUM, which is STRING-kind) is well-formed by construction; its only formal
        // errors are the declared constraints (pattern / enum-domain, then length).
        Kind.STRING -> stringConstraintError(raw, constraints, patternMatches)
        // A boolean stores the exact lowercase `true`/`false`; a confirm has no false, so only `true` is legal
        // (KERNEL-SEMANTICS §1, KERNEL-FINDINGS §2). Both checks are case-SENSITIVE — probe-measured against the
        // kernel, which reports `feldJaNeinFalsch` for `TRUE`/`True` and `feldJaFalsch` for a confirm's `TRUE`
        // (IF229). Case-insensitivity belongs to two OTHER layers: reading a stored value as a `Val.Bool`, and
        // JSON ingress, which normalizes the token before it is ever stored.
        Kind.BOOLEAN -> if (raw == TRUE_TOKEN || raw == FALSE_TOKEN) null else FormalErrorCode.BOOLEAN_INVALID
        Kind.CONFIRM -> if (raw == TRUE_TOKEN) null else FormalErrorCode.CONFIRM_INVALID
    }
}

/**
 * Split a stored DATE_RANGE value the way the kernel's `DateUtil.splitStringBySeparator` does: an **EMPTY**
 * declared separator splits the value in the MIDDLE, any other splits on the token and preserves the empty
 * pieces.
 *
 * **The equivalence is exact for a SINGLE-CHARACTER separator, which is every authorable one.** The kernel
 * delegates to `StringUtils.splitPreserveAllTokens`, whose second argument is a set of separator CHARS rather
 * than a separator string, so a hypothetical multi-character separator would split on each of its characters
 * there and on the whole token here. Every one of the eight admitted `(format, separator)` pairs uses `-`,
 * `/`, or the empty string, so the difference is unreachable — but it is a difference, not an equivalence.
 *
 * The empty separator is not a hypothetical: the declaration's `(format, separator)` PAIR is allowlisted as
 * the concatenation `format + separator + format`, and `MM` + `""` yields `MMMM`, which the kernel admits
 * (measured 2026-08-19 — `MM` is the only format that admits it). So a legal model can carry
 * a `0609` month-pair range, and `raw.split("")` would have shredded it into one piece per character and
 * reported a well-formed value as malformed.
 */
private fun splitDateRange(raw: String, sep: String): List<String> =
    if (sep.isEmpty()) listOf(raw.substring(0, raw.length / 2), raw.substring(raw.length / 2))
    else raw.split(sep)

private const val TRUE_TOKEN = "true"
private const val FALSE_TOKEN = "false"

/**
 * Declared-constraint check for a (well-formed, non-empty) STRING or ENUM value (IF20). The kernel checks the
 * **pattern / enum-domain BEFORE the length** (probe-verified: a value that is both out-of-pattern and too short
 * reports `stringFalschesMuster`, not `stringZuKurz`).
 */
private fun stringConstraintError(
    raw: String,
    c: FieldConstraints,
    patternMatches: (String, String) -> Boolean,
): FormalErrorCode? {
    // `noValueValidation` short-circuits the WHOLE string format check (the kernel's
    // FormatDefinitionString.validiereFormat returns Valid immediately) — so pattern / length / newline are all
    // skipped. A kernel-valid such field carries no pattern/minLength and allows line breaks, so this effectively
    // means a declared maxLength is NOT enforced (IF29).
    if (c.noValueValidation) return null
    // Line break (default-forbidden) FIRST — before enum-domain, pattern, and length (the kernel's
    // `validiereFormat` clause order, IF124). The gate covers ENUM fields too: the kernel's enum format
    // definition hard-codes `lineBreakAllowed = false`, so a break-carrying out-of-domain value is the
    // NEWLINE, never `stringFalschesMuster` (differentially pinned, both strategies).
    if (!c.lineBreaksPermitted && (raw.contains('\n') || raw.contains('\r'))) return FormalErrorCode.NEWLINE
    // An ENUM field's remaining value check is value-domain membership (it has no pattern/length checks).
    if (c.enumValues.isNotEmpty()) {
        return if (raw !in c.enumValues) FormalErrorCode.PATTERN else null   // out-of-domain → stringFalschesMuster
    }
    // A plain STRING: pattern → length. [raw] arrives CRLF-normalized (the Document's eval-ingestion
    // normalization, IF124), so a permitted "\r\n" measures ONE unit here — exactly the kernel, which
    // normalizes inside `validiereFormat` before these clauses.
    if (!c.pattern.isNullOrEmpty() && !patternMatches(c.pattern, raw)) return FormalErrorCode.PATTERN
    if (c.minLength != null && raw.length < c.minLength) return FormalErrorCode.STRING_TOO_SHORT
    // An undeclared maximum is not unbounded: the kernel's generated String format carries 99,999
    // (`ExtmpToolUtils.computeMaxLength`), and a declared one above it is refused at model check. Only a computed
    // value can reach it, because a stored one meets the equal technical limit first (KF547).
    if (raw.length > (c.maxLength ?: DEFAULT_STRING_MAX_LENGTH)) return FormalErrorCode.STRING_TOO_LONG
    return null
}

/** The kernel's fixed technical limit on one stored value, in UTF-16 code units (`FormalChecker.MAX_WERT_LAENGE`). */
internal const val TECHNICAL_VALUE_LIMIT = 99_999

/** The maximum length the kernel gives a String that declares none (`ExtmpToolUtils.DEFAULT_MAX_VALUE_LENGTH`). */
private const val DEFAULT_STRING_MAX_LENGTH = 99_999

/**
 * The input gates of a stored value, in the kernel's order (`FormalChecker.checkAndConvertFieldValue`): the
 * technical length guard over the [authored] text, which counts a CRLF pair as two units, then the baseline. The
 * first failure ends the check. A custom field meets these same gates before its registered validator.
 */
internal fun inputGateError(authored: String, legalCharset: LegalCharset): FormalErrorCode? =
    if (authored.length > TECHNICAL_VALUE_LIMIT) FormalErrorCode.VALUE_TOO_LONG
    else baselineValueError(authored, legalCharset)

/**
 * Declared-constraint check for a (well-formed) NUMBER value (IF20): the minimum-fractional-digits rule (a
 * format-layer concern — too few decimals, or none at all when one is required), then the value range. Range
 * uses the scale-aware [io.github.mbackschat.a12.dm.interpreter.Dec.compareScaled19] compare (the same kernel-
 * matching compare the interpreter uses everywhere).
 */
private fun numberConstraintError(raw: String, c: FieldConstraints): FormalErrorCode? {
    // The kernel's declared-constraint ORDER (FormatDefinitionZahl.validiereFormat, IF67 extended → IF70): the
    // min-fractional-digits rule (missing separator, then too few) → the integer-digit cap → zero-not-allowed →
    // leading zeros (LAST format check) → value-string length → value range. This order is kernel-EXACT: a "0" on
    // a minFrac field is zahlOhneDezimalTrenner (not zahlIstNull), and a leading-zero value that also violates an
    // earlier check reports THAT check (e.g. "07.5" on a scale-0 field is zahlHatDezimalTrenner).
    val minFrac = c.minFractionalDigits ?: 0
    if (minFrac > 0) {
        if (!raw.contains('.')) return FormalErrorCode.NO_DECIMAL_SEPARATOR
        if (fractionalDigits(raw) < minFrac) return FormalErrorCode.TOO_FEW_DECIMALS
    }
    // Integer-digit cap → zahlZuvieleVorkommastellen: the explicit maxIntegerDigits, else the trait:"amount"
    // implicit 15 − scale cap. The kernel's TypeConverter maps BOTH to one `maxDigitsBeforeDecimalPlace` firing
    // the SAME code (amount is not a distinct code). Sign + fractional digits are excluded. (The > 15 TOTAL-digit
    // sanity check `stelligkeitZuLang` fired earlier, in numberFormalError — it precedes this integer-cap check.)
    val intCap = c.maxIntegerDigits ?: c.amountMaxIntegerDigits
    if (intCap != null && integerDigits(raw) > intCap) return FormalErrorCode.TOO_MANY_INTEGER_DIGITS
    // Zero-not-allowed fires AFTER the decimal / integer-cap checks (kernel order): a "0" that also lacks a
    // required separator or overruns the integer cap reports THAT, not zahlIstNull.
    if (c.zeroNotAllowed) decOrNull(raw)?.let { if (it.compareScaled19(DEC_ZERO) == 0) return FormalErrorCode.ZERO_NOT_ALLOWED }
    // Leading zeros are the LAST format check (kernel step 11, after zero-not-allowed) — default-forbidden unless
    // the field declares leadingZerosAllowed. `07`/`00`/`-07`/`00.50` fire; a lone `0` and `0.50` are clean.
    if (!c.leadingZerosAllowed && hasLeadingZeros(raw)) return FormalErrorCode.LEADING_ZEROS
    // Value-string length bounds (the full stored text, incl. sign + decimal point).
    if (c.numberMinLength != null && raw.length < c.numberMinLength) return FormalErrorCode.NUMBER_TOO_SHORT
    if (c.numberMaxLength != null && raw.length > c.numberMaxLength) return FormalErrorCode.NUMBER_TOO_LONG
    val v = decOrNull(raw) ?: return null
    if (c.minValue != null) decOrNull(c.minValue)?.let { if (v.compareScaled19(it) < 0) return FormalErrorCode.NUMBER_TOO_SMALL }
    if (c.maxValue != null) decOrNull(c.maxValue)?.let { if (v.compareScaled19(it) > 0) return FormalErrorCode.NUMBER_TOO_BIG }
    return null
}

/**
 * The parse-level number-format checks the kernel runs regardless of declared constraints, in the kernel's exact
 * `FormatDefinitionZahl.validiereFormat` order: plus-sign → invalid characters → > 15 total digits → signed-zero →
 * decimal-separator (in a scale-0 field) → too-many-decimals (over the scale). The DECLARED-constraint checks —
 * missing/too-few decimals, the integer-digit cap, zero-not-allowed, and (fires LATE, kernel step 11) LEADING
 * ZEROS — all follow in [numberConstraintError], in the kernel's order.
 */
private fun numberFormalError(raw: String, scale: Int?, c: FieldConstraints): FormalErrorCode? = when {
    // (leading/trailing blanks are handled by the cross-kind baselineValueError before this, IF43)
    // A leading `+` on an otherwise-valid number is its own error (the kernel reports it, not "invalid chars").
    raw.startsWith("+") && DECIMAL.matches(raw.drop(1)) -> FormalErrorCode.PLUS_SIGN
    !DECIMAL.matches(raw) -> FormalErrorCode.INVALID_NUMBER
    // The kernel's stelligkeitZuLang — > 15 TOTAL digits (sign + decimal separator excluded) — a generic parse
    // sanity check on EVERY number, right after the invalid-char check and BEFORE the sign/scale checks
    // (FormatDefinitionZahl order — probe-verified it beats signed-zero, leading-zeros, decimal-separator).
    raw.count { it in '0'..'9' } > 15 -> FormalErrorCode.TOTAL_DIGITS_TOO_LONG
    // The two sign classes are DISJOINT, not ordered: the kernel's signed-zero clause conjoins
    // `nullErlaubt && hatVorzeichen`, and the unsigned clause is `!hatVorzeichen` (KF253, measured as a
    // within-model grid). So a signed zero on a zero-FORBIDDING field is not this class — it falls through to
    // `zahlIstNull` in numberConstraintError, and on a scale-0 field to the decimal-separator check first,
    // which is why the "signed-zero beats the separator check" ordering holds only where zero is allowed.
    !c.positivesOnly && !c.zeroNotAllowed && isNegativeZero(raw) -> FormalErrorCode.SIGNED_ZERO
    // The unsigned arm carries one nested exception the kernel spells out: a zero-magnitude value on an
    // unsigned, zero-forbidding MONEY field (`trait:"amount"` → ZahlArt.GELDBETRAG) reports zahlIstNull, while
    // the same declaration without the money trait reports the sign class. A NON-zero negative reports the sign
    // class on both, which is the control that keeps this about the magnitude and not about the trait.
    c.positivesOnly && raw.contains('-') ->
        if (c.amountTrait && c.zeroNotAllowed && isNegativeZero(raw)) FormalErrorCode.ZERO_NOT_ALLOWED
        else FormalErrorCode.SIGN_ON_UNSIGNED
    scale == 0 && raw.contains('.') -> FormalErrorCode.DECIMAL_SEPARATOR
    scale != null && fractionalDigits(raw) > scale -> FormalErrorCode.TOO_MANY_DECIMALS
    else -> null
}

/**
 * The kernel's baseline VALUE checks (`FormalChecker.checkFieldValueFormat`, IF43), run for every checked field
 * kind after the technical length guard ([inputGateError]) and before the type-specific format check, in this order: legal **charset** → **leading** blank → **trailing**
 * blank. With no programming-language charset configured (a DM-JSON model), the default legal charset is the
 * **BMP** (`0x0000-0xFFFF`), so any supplementary-plane character — a UTF-16 surrogate (e.g. an emoji) — is
 * illegal. A leading/trailing blank is reported even when the type check would otherwise pass or fail differently.
 */
internal fun baselineValueError(raw: String, legalCharset: LegalCharset): FormalErrorCode? = when {
    !legalCharset.matches(raw) -> FormalErrorCode.CHARSET
    raw.startsWith(' ') -> FormalErrorCode.LEADING_BLANK
    raw.endsWith(' ') -> FormalErrorCode.TRAILING_BLANK
    else -> null
}

private fun fractionalDigits(raw: String): Int = raw.substringAfter('.', "").length

/** The integer-part digit count of a well-formed number (sign and fractional part excluded): `-1234.5` → 4, `0.50` → 1. */
private fun integerDigits(raw: String): Int = raw.trimStart('-', '+').substringBefore('.').length

/** Whether a well-formed number's integer part has a forbidden leading zero — `07`, `00`, `-07`, `00.50`, `07.50`
 *  (the kernel's `zahlHatFuehrendeNullen`); a lone `0` and `0.50` (integer part `0`) are fine. */
private fun hasLeadingZeros(raw: String): Boolean {
    val intPart = raw.trimStart('-', '+').substringBefore('.')
    return intPart.length > 1 && intPart[0] == '0'
}

/** A minus-signed value whose magnitude is zero (`-0`, `-0.0`, `-0.00`) — the kernel's signed-zero error. */
private fun isNegativeZero(raw: String): Boolean =
    raw.startsWith("-") && raw.drop(1).all { it == '0' || it == '.' }

