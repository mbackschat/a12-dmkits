/** Our OWN end-user text for a non-repeatable group coordinate above its effective maximum 1. */
fun fixedRepetitionText(locale: String): String =
    if (locale.startsWith("de")) "Der Wiederholungsindex einer nicht wiederholbaren Gruppe ist größer als 1."
    else "A non-repeatable group's repetition index is greater than 1."

/** The formal-error checks the interpreter performs, each with the kernel's verbatim [id]. */
enum class FormalErrorCode(val id: String) {
    /** A DATE value that is not `YYYY-MM-DD`. */
    DATE_FORMAT("datumFormatFalsch"),

    /** A lexically well-shaped partial Date whose zero components do not form the required day→month→year
     *  suffix. The kernel uses the same `datumFalsch` id as its concrete-date validity failure. */
    PARTIAL_DATE_INVALID("datumFalsch"),

    /** A well-formed DATE value that resolves to a real calendar date but is BEFORE the kernel's always-on
     *  floor `Constants.DATE_FROM = 1583-10-16` (the start of the Gregorian calendar). The kernel flags it
     *  `datumFalsch` (FEHLER_DATUM) for every stored OR computed date, independent of the opt-in "< 1900"
     *  additional check — confirmed in both strategies (IF88). */
    DATE_TOO_EARLY("datumFalsch"),

    /** ANY field value with a **leading** blank — a baseline value check the kernel runs before the type format
     *  (`checkFieldValueFormat`), for every kind (string/number/date/…). IF43. */
    LEADING_BLANK("fuehrendesBlank"),

    /** ANY field value with a **trailing** blank — the baseline-check sibling of [LEADING_BLANK] (IF43). */
    TRAILING_BLANK("nachfolgendesBlank"),

    /** ANY field value containing a character outside the model's legal charset. With no programming-language
     *  charset configured (a DM-JSON model), the default legal set is the **BMP** (`0x0000-0xFFFF`), so any
     *  SUPPLEMENTARY-plane character (a UTF-16 surrogate pair, e.g. an emoji) is illegal. IF43. */
    CHARSET("ZeichenNichtImZeichensatz"),

    /** A NUMBER value with non-numeric characters. */
    INVALID_NUMBER("zahlHatUngueltigeZeichen"),

    /** A decimal separator in a scale-0 (integer) NUMBER field. */
    DECIMAL_SEPARATOR("zahlHatDezimalTrenner"),

    /** More fractional digits than the NUMBER field's scale allows. */
    TOO_MANY_DECIMALS("zahlFalscheAnzahlNachkommastellen"),

    /** A NUMBER zero carrying a minus sign (`-0`, `-0.00`) — the kernel forbids a signed zero. */
    SIGNED_ZERO("zahlNullEnthaeltVorzeichen"),

    /** A NUMBER with a leading plus sign (`+5`, `+0`) — the kernel forbids an explicit plus. */
    PLUS_SIGN("zahlMitPlus"),

    /** A DATE_RANGE value whose separator is missing or misplaced (it does not split into exactly two dates). */
    DATE_RANGE_SEPARATOR("datumBereichTrennerFehlt"),

    /** A DATE_RANGE value split in two, but a side is not a valid date for the field's format. */
    DATE_RANGE_FORMAT("datumBereichFormatFalsch"),

    /** A DATE_RANGE with two valid dates, but the start is AFTER the end (start == end is allowed). */
    DATE_RANGE_INVALID("datumBereichNichtGueltig"),

    /** A DATE_RANGE whose START date is before the Gregorian-calendar floor (1583-10-16) — the range sibling
     *  of [DATE_TOO_EARLY] (`FormatDefinitionDatumBereich extends FormatDefinitionDatum`; the kernel floors the
     *  start, and end >= start covers the end). Kernel code `datumBereichDatumFalsch` (FEHLER_DATUM_BEREICH_DATUM). */
    DATE_RANGE_TOO_EARLY("datumBereichDatumFalsch"),

    // ── Declared field-type CONSTRAINT violations (IF20) — auto-fired against the field-type declaration,
    //    same `formalePruefung` mechanism as the format checks above (KERNEL-FINDINGS §3 "declared field-type
    //    constraints"). Each carries the kernel's verbatim runtime code; all are VALUE errors. ──
    /** A STRING shorter than the field's declared `minLength` (the kernel's `stringZuKurz`). */
    STRING_TOO_SHORT("stringZuKurz"),

    /** A STRING longer than the field's declared `maxLength` (the kernel's `stringZuLang`). */
    STRING_TOO_LONG("stringZuLang"),

    /** A STRING not matching the field's declared `pattern`, OR an ENUM value not in the field's value domain
     *  (both → the kernel's `stringFalschesMuster`; the pattern/domain check runs BEFORE the length checks). */
    PATTERN("stringFalschesMuster"),

    /** A NUMBER below the field's declared `minValue` (the kernel's `zahlZuKlein`). */
    NUMBER_TOO_SMALL("zahlZuKlein"),

    /** A NUMBER above the field's declared `maxValue` (the kernel's `zahlZuGross`). */
    NUMBER_TOO_BIG("zahlZuGross"),

    /** A NUMBER with a decimal point but FEWER fractional digits than `minFractionalDigits` — the kernel's
     *  `zahlFalscheAnzahlNachkommastellen` (the SAME code as [TOO_MANY_DECIMALS]; "wrong number of decimals"). */
    TOO_FEW_DECIMALS("zahlFalscheAnzahlNachkommastellen"),

    /** A NUMBER with NO decimal point where `minFractionalDigits > 0` requires one (the kernel's
     *  `zahlOhneDezimalTrenner` — "number without decimal separator"). */
    NO_DECIMAL_SEPARATOR("zahlOhneDezimalTrenner"),

    /** A STRING containing a line break where the field does not permit them (the kernel's `stringMitNewline`).
     *  **Default-forbidden** — fires unless the field declares `lineBreaksPermitted: true` (an ENUM never can —
     *  its kernel format definition hard-codes `lineBreakAllowed = false`). Checked as a format concern, the
     *  FIRST value clause — before enum-domain, pattern, and the length checks (differentially pinned, IF124). */
    NEWLINE("stringMitNewline"),

    /** A NUMBER whose integer part carries a forbidden leading zero (`07`, `00`, `00.50`; the kernel's
     *  `zahlHatFuehrendeNullen`). **Default-forbidden** — fires unless the field declares `leadingZerosAllowed:
     *  true`. A lone `0` and `0.50` (integer part `0`) are fine. */
    LEADING_ZEROS("zahlHatFuehrendeNullen"),

    /** A NUMBER equal to zero where the field declares `zeroNotAllowed: true` (the kernel's `zahlIstNull`). */
    ZERO_NOT_ALLOWED("zahlIstNull"),

    /** A NUMBER whose INTEGER-part digit count exceeds the field's integer-digit cap — the kernel's
     *  `zahlZuvieleVorkommastellen`. The cap is the explicit `maxIntegerDigits`, or (when unset) a `trait:"amount"`
     *  field's implicit `15 − maxFractionalDigits`: the kernel's `TypeConverter` maps BOTH to the one
     *  `maxDigitsBeforeDecimalPlace` cap firing the one code (amount is not a separate code). Sign and fractional
     *  digits are excluded from the count; checked AFTER the [TOTAL_DIGITS_TOO_LONG] parse check. */
    TOO_MANY_INTEGER_DIGITS("zahlZuvieleVorkommastellen"),

    /** A NUMBER with MORE THAN 15 TOTAL digits (integer + fractional, sign and decimal separator excluded) — the
     *  kernel's `stelligkeitZuLang`. This is a GENERIC parse-time sanity check on EVERY number (the kernel's
     *  `FormatDefinitionZahl.validiereFormat` / `NumberConversion.sanityCheck`), NOT a `trait:"amount"` concern:
     *  it fires right after the invalid-character check and BEFORE the sign / scale / leading-zero / integer-cap
     *  checks (probe-verified it beats leading-zeros, the decimal-separator check, and signed-zero). */
    TOTAL_DIGITS_TOO_LONG("stelligkeitZuLang"),

    /** A NUMBER whose value-string length is below the field's declared `minLength` (the kernel's `zahlZuKurz`);
     *  the length counts the full stored text incl. sign and decimal point. */
    NUMBER_TOO_SHORT("zahlZuKurz"),

    /** A NUMBER whose value-string length exceeds the field's declared `maxLength` (the kernel's `zahlZuLang`). */
    NUMBER_TOO_LONG("zahlZuLang"),

    /** A BOOLEAN token other than the exact lowercase `true` / `false` — the kernel's `feldJaNeinFalsch`. The
     *  check is **case-SENSITIVE**: `TRUE`, `FALSE`, and `True` are all formally invalid, as are `yes`/`1`/`0`.
     *  (Distinct from the *evaluation* of an already-stored value, which reads case-insensitively; and from JSON
     *  ingress, which normalizes `"TRUE"` to `true` before storage, exactly as A12's converter does — so this
     *  fires on the internal path where a caller fills a `Document` directly. Probe-measured, IF229.) */
    BOOLEAN_INVALID("feldJaNeinFalsch"),

    /** A CONFIRM token other than the exact lowercase `true` — the kernel's `feldJaFalsch`. A confirm has no
     *  false: a well-formed `false` is a formal error, as are `TRUE`, `yes`, and `1` (probe-measured, IF229). */
    CONFIRM_INVALID("feldJaFalsch"),
}

fun formalError(
    kind: Kind, raw: String, scale: Int? = null, format: String? = null,
    datePrecision: DatePrecision = DatePrecision.FULL, rangeSep: String? = null,
    constraints: FieldConstraints = FieldConstraints.NONE,
    legalCharset: LegalCharset = LegalCharset.BMP,
    /** The model's base year (kernel default 2000) — the year a year-less date FRAGMENT (`MM`, `MM-dd`)
     *  completes to for its realness check; unused for non-fragment kinds. */
    baseYear: Int = 2000,
    /** The model's configured time zone — a Europe/Berlin DATE_TIME inside the spring-forward gap is
     *  `datumFormatFalsch` (the kernel's non-lenient zone-set parse rejects it; KERNEL-FINDINGS §6). */
    timeZone: ModelTimeZone = ModelTimeZone.UTC,
): FormalErrorCode? {
    return formalErrorCached(
        kind, raw, scale, format, datePrecision, rangeSep, constraints, legalCharset, baseYear, timeZone,
    ) { pattern, value -> compilePattern(pattern).matches(value) }
}

internal fun formalErrorCached(
    kind: Kind, raw: String, scale: Int? = null, format: String? = null,
    datePrecision: DatePrecision = DatePrecision.FULL, rangeSep: String? = null,
    constraints: FieldConstraints = FieldConstraints.NONE,
    legalCharset: LegalCharset = LegalCharset.BMP,
    baseYear: Int = 2000,
    timeZone: ModelTimeZone = ModelTimeZone.UTC,
    patternMatches: (String, String) -> Boolean,
): FormalErrorCode? {
    if (raw.isEmpty()) return null
    // BASELINE value checks the kernel runs for EVERY kind before the type format (`checkFieldValueFormat`,
    // IF43): legal charset (default BMP; [legalCharset] customizes it, e.g. DIN 91379), then leading blank, then
    // trailing blank. They pre-empt the type-specific check (a ` 2024-01-01` DATE is `fuehrendesBlank`).
    baselineValueError(raw, legalCharset)?.let { return it }
    return typeFormatErrorCached(
        kind, raw, scale, format, datePrecision, rangeSep, constraints, baseYear, timeZone, patternMatches,
    )
}

/**
 * The TYPE-format half of [formalError] alone — the kernel's `checkFieldValueFormatBasic` (only
 * `IFormatDefinition.validiereFormat`, no baseline checks). This is the check a COMPUTED value gets
 * (`CalculationController.checkField` inside every `handleBerechnetenWert` overload): a computed result may
 * legally start/end with a blank or carry any charset — only its type format and declared constraints decide
 * "fehlerhaft berechnet" (`FieldValueAsStringComputeDiffTest`). Stored INPUT values take [formalError] (the
 * kernel's full `checkFieldValueFormat` = charset → leading blank → trailing blank → this).
 */
fun typeFormatError(
    kind: Kind, raw: String, scale: Int? = null, format: String? = null,
    datePrecision: DatePrecision = DatePrecision.FULL, rangeSep: String? = null,
    constraints: FieldConstraints = FieldConstraints.NONE,
    baseYear: Int = 2000,
    timeZone: ModelTimeZone = ModelTimeZone.UTC,
): FormalErrorCode? {
    return typeFormatErrorCached(
        kind, raw, scale, format, datePrecision, rangeSep, constraints, baseYear, timeZone,
    ) { pattern, value -> compilePattern(pattern).matches(value) }
}

internal fun typeFormatErrorCached(
    kind: Kind, raw: String, scale: Int? = null, format: String? = null,
    datePrecision: DatePrecision = DatePrecision.FULL, rangeSep: String? = null,
    constraints: FieldConstraints = FieldConstraints.NONE,
    baseYear: Int = 2000,
    timeZone: ModelTimeZone = ModelTimeZone.UTC,
    patternMatches: (String, String) -> Boolean,
): FormalErrorCode? {
    if (raw.isEmpty()) return null
    return when (kind) {
        // Format-aware: a value valid for the field's DECLARED format is well-formed (a `dd.MM.yyyy` field's
        // `15.06.2024` is fine — not ISO, but valid for its format). Null format defaults to ISO (KERNEL-FINDINGS
        // plain-date locale handling, PlainDateDiffTest). Precision widens what "valid" means: partial DateType
        // omissions form the day→month→year suffix; a FRAGMENT is well-formed iff its value parses in its
        // (partial) format with real components (`completeFragmentToIso`) — a `2024-13` yyyy-MM is malformed.
        Kind.DATE -> {
            val fmt = format ?: ISO_FORMAT
            val invalidPartialShape = when (datePrecision) {
                DatePrecision.DAY_OPTIONAL,
                DatePrecision.MONTH_OPTIONAL,
                DatePrecision.YEAR_OPTIONAL,
                -> invalidPartialDateOmissionShape(raw, fmt, datePrecision)
                DatePrecision.FULL, DatePrecision.FRAGMENT -> false
            }
            // The formal check temporarily replaces every admitted unknown component with 2000/01/01 before
            // the ordinary date checks. Evaluation never receives that synthetic year.
            val parts = when (datePrecision) {
                DatePrecision.DAY_OPTIONAL,
                DatePrecision.MONTH_OPTIONAL,
                DatePrecision.YEAR_OPTIONAL,
                -> partialDateParts(raw, fmt, datePrecision)?.let { (y, m, d) ->
                    Triple(if (y == 0) 2000 else y, if (m == 0) 1 else m, if (d == 0) 1 else d)
                }
                DatePrecision.FRAGMENT -> completeFragmentToIso(raw, fmt, baseYear)?.let { dateParts(it) }
                DatePrecision.FULL -> {
                    // A DateType with exact format `yyyy` is a kernel-legal complete-Year component source.
                    // It is not a DateFragmentType, but its own field value must pass the formal gate before
                    // Date(...) can route the stored year through numeric conversion (SPEC-2026-07-27-13).
                    // Keep the exception exact: other incomplete DateType formats are not inferred here.
                    val iso = if (fmt == "yyyy") completeFragmentToIso(raw, fmt, baseYear)
                    else parseDateToIso(raw, fmt)
                    iso?.let { dateParts(it) }
                }
            }
            when {
                invalidPartialShape -> FormalErrorCode.PARTIAL_DATE_INVALID
                parts == null -> FormalErrorCode.DATE_FORMAT
                // The kernel's always-on Gregorian floor (IF88): a real date before 1583-10-16 is `datumFalsch`.
                beforeGregorianStart(parts.first, parts.second, parts.third) -> FormalErrorCode.DATE_TOO_EARLY
                else -> null
            }
        }
        // Format well-formedness FIRST (blanks, invalid chars, signed-zero/plus, decimal-separator,
        // too-MANY decimals via scale); only a well-formed number reaches the declared-constraint checks
        // (min fractional digits, then range) — KERNEL-FINDINGS §3 precedence.
        Kind.NUMBER -> numberFormalError(raw, scale) ?: numberConstraintError(raw, constraints)
        // A malformed TIME / DATE_TIME value carries the kernel's `datumFormatFalsch` (probe-verified — the same
        // code as DATE), and resolving it to Val.Unknown suppresses a referencing rule. (TIME was previously
        // unchecked entirely, so a malformed time even *escaped* suppression — KERNEL-FINDINGS §6 / IF8.)
        Kind.TIME -> if (parseTimeToIso(raw, format ?: "HH:mm:ss") != null) null else FormalErrorCode.DATE_FORMAT
        Kind.DATE_TIME -> {
            val iso = parseDateTimeToIso(raw, format ?: "yyyy-MM-dd'T'HH:mm:ss")
            when {
                iso == null -> FormalErrorCode.DATE_FORMAT
                // A Europe/Berlin wall time inside the spring-forward gap does not exist — the kernel's
                // non-lenient zone-set parse rejects it with the SAME code (probe-verified, KERNEL-FINDINGS §6).
                isGapLocal(iso, timeZone) -> FormalErrorCode.DATE_FORMAT
                else -> null
            }
        }
        // A malformed DATE_RANGE carries one of the kernel's `datumBereich*` codes (probe-verified): a value that
        // does not split into exactly two parts on the separator → `datumBereichTrennerFehlt`; split but a side
        // is not a valid date for the format (incl. calendar-invalid like 31.02) → `datumBereichFormatFalsch`;
        // two valid dates but start AFTER end → `datumBereichNichtGueltig` (start == end is allowed). A malformed
        // range also resolves to Val.Unknown, suppressing a referencing rule. Each side parses BY THE DECLARED
        // format, whatever its granularity — a FRAGMENT format (a `yyyy` year-range like `2024/2025`, a real
        // workspace idiom) completes to its earliest concrete date exactly like a fragment DATE field
        // (`FragmentRangeFormalDiffTest`).
        Kind.DATE_RANGE -> {
            if (format == null || rangeSep == null) null   // no range config → nothing to check
            else {
                val parts = raw.split(rangeSep)
                when {
                    parts.size != 2 -> FormalErrorCode.DATE_RANGE_SEPARATOR
                    else -> {
                        val a = parseDateToIso(parts[0], format) ?: completeFragmentToIso(parts[0], format, baseYear)
                        val b = parseDateToIso(parts[1], format) ?: completeFragmentToIso(parts[1], format, baseYear)
                        when {
                            a == null || b == null -> FormalErrorCode.DATE_RANGE_FORMAT
                            a > b -> FormalErrorCode.DATE_RANGE_INVALID   // ISO strings: lexicographic == chronological
                            // The kernel floors the range START at 1583-10-16 (IF88); end >= start covers the end.
                            dateParts(a)?.let { (y, m, d) -> beforeGregorianStart(y, m, d) } == true ->
                                FormalErrorCode.DATE_RANGE_TOO_EARLY
                            else -> null
                        }
                    }
                }
            }
        }
        // A STRING (incl. an ENUM, which is STRING-kind) is well-formed by construction; its only formal
        // errors are the declared constraints (pattern / enum-domain, then length).
        Kind.STRING -> stringConstraintError(raw, constraints, patternMatches)
        // A boolean stores the exact lowercase `true`/`false`; a confirm has no false, so only `true` is legal
        // (KERNEL-SEMANTICS §1, KERNEL-FINDINGS §2). Both checks are case-SENSITIVE — probe-measured against the
        // kernel, which reports `feldJaNeinFalsch` for `TRUE`/`True` and `feldJaFalsch` for a confirm's `TRUE`
        // (IF229). Case-insensitivity belongs to two OTHER layers: reading a stored value as a `Val.Bool`, and
        // JSON ingress, which normalizes the token before it is ever stored.
        Kind.BOOLEAN -> if (raw == TRUE_TOKEN || raw == FALSE_TOKEN) null else FormalErrorCode.BOOLEAN_INVALID
        Kind.CONFIRM -> if (raw == TRUE_TOKEN) null else FormalErrorCode.CONFIRM_INVALID
    }
}

private const val TRUE_TOKEN = "true"
private const val FALSE_TOKEN = "false"

/**
 * Declared-constraint check for a (well-formed, non-empty) STRING or ENUM value (IF20). The kernel checks the
 * **pattern / enum-domain BEFORE the length** (probe-verified: a value that is both out-of-pattern and too short
 * reports `stringFalschesMuster`, not `stringZuKurz`).
 */
private fun stringConstraintError(
    raw: String,
    c: FieldConstraints,
    patternMatches: (String, String) -> Boolean,
): FormalErrorCode? {
    // `noValueValidation` short-circuits the WHOLE string format check (the kernel's
    // FormatDefinitionString.validiereFormat returns Valid immediately) — so pattern / length / newline are all
    // skipped. A kernel-valid such field carries no pattern/minLength and allows line breaks, so this effectively
    // means a declared maxLength is NOT enforced (IF29).
    if (c.noValueValidation) return null
    // Line break (default-forbidden) FIRST — before enum-domain, pattern, and length (the kernel's
    // `validiereFormat` clause order, IF124). The gate covers ENUM fields too: the kernel's enum format
    // definition hard-codes `lineBreakAllowed = false`, so a break-carrying out-of-domain value is the
    // NEWLINE, never `stringFalschesMuster` (differentially pinned, both strategies).
    if (!c.lineBreaksPermitted && (raw.contains('\n') || raw.contains('\r'))) return FormalErrorCode.NEWLINE
    // An ENUM field's remaining value check is value-domain membership (it has no pattern/length checks).
    if (c.enumValues.isNotEmpty()) {
        return if (raw !in c.enumValues) FormalErrorCode.PATTERN else null   // out-of-domain → stringFalschesMuster
    }
    // A plain STRING: pattern → length. [raw] arrives CRLF-normalized (the Document's eval-ingestion
    // normalization, IF124), so a permitted "\r\n" measures ONE unit here — exactly the kernel, which
    // normalizes inside `validiereFormat` before these clauses.
    if (c.pattern != null && !patternMatches(c.pattern, raw)) return FormalErrorCode.PATTERN
    if (c.minLength != null && raw.length < c.minLength) return FormalErrorCode.STRING_TOO_SHORT
    if (c.maxLength != null && raw.length > c.maxLength) return FormalErrorCode.STRING_TOO_LONG
    return null
}

/**
 * Declared-constraint check for a (well-formed) NUMBER value (IF20): the minimum-fractional-digits rule (a
 * format-layer concern — too few decimals, or none at all when one is required), then the value range. Range
 * uses the scale-aware [io.github.mbackschat.a12.dm.interpreter.Dec.compareScaled19] compare (the same kernel-
 * matching compare the interpreter uses everywhere).
 */
private fun numberConstraintError(raw: String, c: FieldConstraints): FormalErrorCode? {
    // The kernel's declared-constraint ORDER (FormatDefinitionZahl.validiereFormat, IF67 extended → IF70): the
    // min-fractional-digits rule (missing separator, then too few) → the integer-digit cap → zero-not-allowed →
    // leading zeros (LAST format check) → value-string length → value range. This order is kernel-EXACT: a "0" on
    // a minFrac field is zahlOhneDezimalTrenner (not zahlIstNull), and a leading-zero value that also violates an
    // earlier check reports THAT check (e.g. "07.5" on a scale-0 field is zahlHatDezimalTrenner).
    val minFrac = c.minFractionalDigits ?: 0
    if (minFrac > 0) {
        if (!raw.contains('.')) return FormalErrorCode.NO_DECIMAL_SEPARATOR
        if (fractionalDigits(raw) < minFrac) return FormalErrorCode.TOO_FEW_DECIMALS
    }
    // Integer-digit cap → zahlZuvieleVorkommastellen: the explicit maxIntegerDigits, else the trait:"amount"
    // implicit 15 − scale cap. The kernel's TypeConverter maps BOTH to one `maxDigitsBeforeDecimalPlace` firing
    // the SAME code (amount is not a distinct code). Sign + fractional digits are excluded. (The > 15 TOTAL-digit
    // sanity check `stelligkeitZuLang` fired earlier, in numberFormalError — it precedes this integer-cap check.)
    val intCap = c.maxIntegerDigits ?: c.amountMaxIntegerDigits
    if (intCap != null && integerDigits(raw) > intCap) return FormalErrorCode.TOO_MANY_INTEGER_DIGITS
    // Zero-not-allowed fires AFTER the decimal / integer-cap checks (kernel order): a "0" that also lacks a
    // required separator or overruns the integer cap reports THAT, not zahlIstNull.
    if (c.zeroNotAllowed) decOrNull(raw)?.let { if (it.compareScaled19(DEC_ZERO) == 0) return FormalErrorCode.ZERO_NOT_ALLOWED }
    // Leading zeros are the LAST format check (kernel step 11, after zero-not-allowed) — default-forbidden unless
    // the field declares leadingZerosAllowed. `07`/`00`/`-07`/`00.50` fire; a lone `0` and `0.50` are clean.
    if (!c.leadingZerosAllowed && hasLeadingZeros(raw)) return FormalErrorCode.LEADING_ZEROS
    // Value-string length bounds (the full stored text, incl. sign + decimal point).
    if (c.numberMinLength != null && raw.length < c.numberMinLength) return FormalErrorCode.NUMBER_TOO_SHORT
    if (c.numberMaxLength != null && raw.length > c.numberMaxLength) return FormalErrorCode.NUMBER_TOO_LONG
    val v = decOrNull(raw) ?: return null
    if (c.minValue != null) decOrNull(c.minValue)?.let { if (v.compareScaled19(it) < 0) return FormalErrorCode.NUMBER_TOO_SMALL }
    if (c.maxValue != null) decOrNull(c.maxValue)?.let { if (v.compareScaled19(it) > 0) return FormalErrorCode.NUMBER_TOO_BIG }
    return null
}

/**
 * The parse-level number-format checks the kernel runs regardless of declared constraints, in the kernel's exact
 * `FormatDefinitionZahl.validiereFormat` order: plus-sign → invalid characters → > 15 total digits → signed-zero →
 * decimal-separator (in a scale-0 field) → too-many-decimals (over the scale). The DECLARED-constraint checks —
 * missing/too-few decimals, the integer-digit cap, zero-not-allowed, and (fires LATE, kernel step 11) LEADING
 * ZEROS — all follow in [numberConstraintError], in the kernel's order.
 */
private fun numberFormalError(raw: String, scale: Int?): FormalErrorCode? = when {
    // (leading/trailing blanks are handled by the cross-kind baselineValueError before this, IF43)
    // A leading `+` on an otherwise-valid number is its own error (the kernel reports it, not "invalid chars").
    raw.startsWith("+") && DECIMAL.matches(raw.drop(1)) -> FormalErrorCode.PLUS_SIGN
    !DECIMAL.matches(raw) -> FormalErrorCode.INVALID_NUMBER
    // The kernel's stelligkeitZuLang — > 15 TOTAL digits (sign + decimal separator excluded) — a generic parse
    // sanity check on EVERY number, right after the invalid-char check and BEFORE the sign/scale checks
    // (FormatDefinitionZahl order — probe-verified it beats signed-zero, leading-zeros, decimal-separator).
    raw.count { it in '0'..'9' } > 15 -> FormalErrorCode.TOTAL_DIGITS_TOO_LONG
    // Signed-zero is checked BEFORE the scale/separator checks (verified: `-0.0` on a scale-0 field is the
    // signed-zero error, NOT the decimal-separator one — kernel order, NumberSignFormalDiffTest).
    isNegativeZero(raw) -> FormalErrorCode.SIGNED_ZERO
    scale == 0 && raw.contains('.') -> FormalErrorCode.DECIMAL_SEPARATOR
    scale != null && fractionalDigits(raw) > scale -> FormalErrorCode.TOO_MANY_DECIMALS
    else -> null
}

/**
 * The kernel's baseline VALUE checks (`FormalChecker.checkFieldValueFormat`, IF43), run for EVERY field kind
 * before the type-specific format check, in this order: legal **charset** → **leading** blank → **trailing**
 * blank. With no programming-language charset configured (a DM-JSON model), the default legal charset is the
 * **BMP** (`0x0000-0xFFFF`), so any supplementary-plane character — a UTF-16 surrogate (e.g. an emoji) — is
 * illegal. A leading/trailing blank is reported even when the type check would otherwise pass or fail differently.
 */
private fun baselineValueError(raw: String, legalCharset: LegalCharset): FormalErrorCode? = when {
    !legalCharset.matches(raw) -> FormalErrorCode.CHARSET
    raw.startsWith(' ') -> FormalErrorCode.LEADING_BLANK
    raw.endsWith(' ') -> FormalErrorCode.TRAILING_BLANK
    else -> null
}

private fun fractionalDigits(raw: String): Int = raw.substringAfter('.', "").length

/** The integer-part digit count of a well-formed number (sign and fractional part excluded): `-1234.5` → 4, `0.50` → 1. */
private fun integerDigits(raw: String): Int = raw.trimStart('-', '+').substringBefore('.').length

/** Whether a well-formed number's integer part has a forbidden leading zero — `07`, `00`, `-07`, `00.50`, `07.50`
 *  (the kernel's `zahlHatFuehrendeNullen`); a lone `0` and `0.50` (integer part `0`) are fine. */
private fun hasLeadingZeros(raw: String): Boolean {
    val intPart = raw.trimStart('-', '+').substringBefore('.')
    return intPart.length > 1 && intPart[0] == '0'
}

/** A minus-signed value whose magnitude is zero (`-0`, `-0.0`, `-0.00`) — the kernel's signed-zero error. */
private fun isNegativeZero(raw: String): Boolean =
    raw.startsWith("-") && raw.drop(1).all { it == '0' || it == '.' }

