package io.github.mbackschat.a12.dm;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

import org.junit.jupiter.api.Test;

/**
 * <b>Data that must survive a build never lives under {@code build/}</b> (CLAUDE.md, owner rule 2026-08-11).
 *
 * <p><b>Why a guard rather than a note.</b> A {@code build/} directory is gitignored and deleted by {@code clean},
 * so anything written there is gone at the next clean and invisible to git. That is correct for derived output and
 * catastrophic for a record. It shipped exactly once: the performance gate wrote every measured median to a file
 * under {@code adapter/build/}, which meant the estate could compare a run against one committed anchor but could
 * never compare it against its own history, because the history was deleted on a schedule. The fix was to move the
 * record; this guard is what stops the next one.
 *
 * <p><b>The rule as enforced.</b> Every source-level construction of a path under {@code build/} must be declared
 * in {@link #DECLARED}, with the {@link BuildPathUse} it serves and the reason that use is safe. An undeclared one
 * fails, with the three ways out named in the message. This is the classify-or-fail shape the CLI's contract
 * exemptions already use, so a new site cannot pass silently.
 *
 * <p>The declarations are also asserted to be <b>fully used</b>: if a declared site disappears, the entry must go
 * too, which keeps the list from decaying into stale permissions that quietly widen the rule. That assertion is a
 * positive control as well — it can only pass if the scan really reached those files and really matched.
 *
 * <p><b>Recall limits, stated rather than implied.</b> Two are deliberate. (1) The scan reads {@code .kt}/{@code
 * .java} only. Shell and Gradle sources name <b>45</b> distinct {@code build/} paths across 77 occurrences
 * (2026-08-16), essentially all of them legitimate derived
 * output (install dists, native binaries, release staging, reports); requiring a declaration for each would turn
 * this list into a set of permissions nobody reviews, which is the failure mode the fully-used assertion exists to
 * prevent. (2) A single-literal path is only a candidate when a path-constructing call ({@link #PATH_APIS}) appears within
 * {@link #API_WINDOW} characters before it, so message text and regex patterns that merely mention {@code build/}
 * are not declarations to maintain, and a literal containing whitespace is prose rather than a path. Comments are stripped before matching, so a doc comment may freely illustrate
 * the pattern — for instance {@code Path.of("build/whatever")} right here, which the earlier constructor-anchored
 * matcher would have flagged against this very file.
 */
class SurvivingDataNotInBuildGuardTest {

    /** What a {@code build/} path literal in source actually does, since not every one of them is a write. */
    private enum BuildPathUse {
        /** A real write whose loss at {@code clean} is harmless: output regenerated by whoever needs it next. */
        WRITES_TRANSIENT_OUTPUT,
        /** No write at all — the path is read, so {@code clean} costs nothing that was not already derived. */
        READS_DERIVED_OUTPUT,
    }

    private record Declaration(BuildPathUse use, String reason) {
        Declaration {
            if (reason == null || reason.isBlank()) {
                throw new IllegalArgumentException("a declared build/ path must say why its use is safe");
            }
        }
    }

    /** Every path literal under {@code build/} the scan may see, with its use and the reason that use is safe. */
    private static final Checkout CHECKOUT = Checkout.locate();

    private static final Map<String, Declaration> DECLARED = new LinkedHashMap<>(Map.of(
            "build/perf-progress.log",
            new Declaration(BuildPathUse.WRITES_TRANSIENT_OUTPUT,
                    "a tailable live progress log, truncated once per JVM so each run starts clean; it exists "
                            + "because Gradle buffers captured stdout until a task ends, and it carries no "
                            + "measurement — the measurements go to the committed perf-results tree"),
            "build/rp-large.dm.json",
            new Declaration(BuildPathUse.WRITES_TRANSIENT_OUTPUT,
                    "a generated fixture for a manual before/after CLI comparison under -Drp.perf=true; "
                            + "regenerated by the test that consumes it"),
            "build/profile-interpreter-performance",
            new Declaration(BuildPathUse.WRITES_TRANSIENT_OUTPUT,
                    "the default output directory for a synthesized profiling model; the synthesis is "
                            + "deterministic in its seed, so the model is reproduced rather than recovered"),
            "build/reports/capability-evidence/certificate-summary.md",
            new Declaration(BuildPathUse.WRITES_TRANSIENT_OUTPUT,
                    "a generated report of the capability-evidence matrix, rewritten from the matrix on every run "
                            + "of the test that produces it, and read back only by that same test"),
            "build/classes/java/main",
            new Declaration(BuildPathUse.READS_DERIVED_OUTPUT,
                    "the compiled main classes the public-API dump READS; the golden it compares against lives "
                            + "in the committed api/ tree, which is the thing that must survive"),
            "build/classes/kotlin/main",
            new Declaration(BuildPathUse.READS_DERIVED_OUTPUT,
                    "the same dump, for the one published module the Kotlin compiler builds; its golden lives "
                            + "beside the others in the committed api/ tree")));

    /**
     * A string literal naming a path under {@code build/}. Bare {@code "build/"} is excluded by the trailing
     * {@code +}: it is a directory-name comparison, never a file this rule can be about.
     */
    private static final Pattern BUILD_PATH_LITERAL = Pattern.compile("\"([^\"\\n]*build/[^\"\\n]+)\"");

    /**
     * The SEGMENT-WISE form: {@code Path.of("build", "reports", …)}. No literal contains {@code build/} at all,
     * so {@link #BUILD_PATH_LITERAL} cannot see it — and it is the natural idiom, which is how a live write site
     * sat undeclared. The trailing literals are re-joined with {@code /} so it declares like any other path.
     */
    private static final Pattern BUILD_PATH_SEGMENTS =
            Pattern.compile("(?:File|Path\\.of|Paths\\.get)\\(\\s*\"build\"((?:\\s*,\\s*\"[^\"\\n]*\")+)");

    private static final Pattern SEGMENT = Pattern.compile("\"([^\"\\n]*)\"");

    /** Calls that turn a string into a filesystem path. A literal reached by none of them is not a path. */
    private static final List<String> PATH_APIS =
            List.of("File(", "Path.of(", "Paths.get(", "FileWriter(", "FileOutputStream(",
                    "RandomAccessFile(", ".resolve(");

    /**
     * How far back a path-constructing call may sit and still own the literal. Wide enough for the literal to be
     * the default argument of a nested lookup spanning lines — {@code Path.of(System.getProperty(key, "build/x"))}
     * is the live shape that the earlier matcher, which demanded the literal be the FIRST argument, could not see.
     */
    private static final int API_WINDOW = 200;


    /**
     * Excluded directory names, matched as whole path SEGMENTS of the repo-relative path — never as a substring of
     * the absolute one. Both halves of that sentence are load-bearing, and getting either wrong makes the scan
     * silently empty rather than loud: this project's own worktrees live under {@code .claude/worktrees/<name>},
     * so inside one every absolute path contains {@code /.claude/} and a substring test excludes the entire
     * repository. The scan then finds nothing, {@link #noSourceWritesSurvivingDataUnderBuild}'s undeclared-site
     * assertion passes over zero files, and only the declarations-used half fails — which reads as a stale
     * permission and invites deleting a live entry.
     */
    private static List<Path> sources() {
        return CHECKOUT.sources();
    }

    @Test
    void noSourceWritesSurvivingDataUnderBuild() throws IOException {
        List<Path> sources = sources();
        // Before anything is concluded from the scan: prove it HAPPENED. Every assertion below is satisfied by an
        // empty scan, so a filter that excludes the whole tree reads as "no violations" plus one confusing
        // declarations failure. That is the exact shape this guard shipped in, and it survived because the loud
        // half pointed at the innocent list rather than at the scan.
        assertTrue(sources.size() > 100, () -> "the source scan collapsed to " + sources.size() + " file(s); every "
                + "other assertion here is vacuously true over an empty scan, so this is a broken filter (see "
                + "EXCLUDED_SEGMENTS), never a clean repository");

        var undeclared = new ArrayList<String>();
        var seen = new ArrayList<String>();
        for (Path source : sources) {
            // Kotlin nests block comments; Java does NOT. Applying Kotlin's rule to Java is not a harmless
            // over-approximation: one `/*` inside a Javadoc — `{@code build/*-red.log}` is a real occurrence in
            // this very repository — drives the depth to 2, so the closing `*/` only returns it to 1 and the
            // REST OF THE FILE is treated as comment. Measured before the fix: 10 Java files ended in a
            // non-neutral state and 1,179 lines of real code were blanked, any write site among them invisible.
            String code = withoutComments(Files.readString(source), source.getFileName().toString().endsWith(".kt"));
            Matcher found = BUILD_PATH_LITERAL.matcher(code);
            while (found.find()) {
                if (looksLikeAPath(found.group(1)) && constructedAsPath(code, found.start())) {
                    classify(found.group(1), source, seen, undeclared);
                }
            }
            Matcher segments = BUILD_PATH_SEGMENTS.matcher(code);
            while (segments.find()) {
                var joined = new StringBuilder("build");
                Matcher segment = SEGMENT.matcher(segments.group(1));
                while (segment.find()) {
                    joined.append('/').append(segment.group(1));
                }
                classify(joined.toString(), source, seen, undeclared);
            }
        }

        assertTrue(undeclared.isEmpty(), () -> "a build/ directory is gitignored and deleted by `clean`, so data "
                + "written there cannot survive and cannot be compared against its own history (CLAUDE.md: never "
                + "store surviving data under build/). Undeclared path site(s):\n  " + String.join("\n  ", undeclared)
                + "\n\nThree ways out: write it to a COMMITTED directory (the performance record's own fix was "
                + "perf-results/); declare it "
                + BuildPathUse.WRITES_TRANSIENT_OUTPUT + " with the reason losing it is harmless; or, if nothing is "
                + "written at all, declare it " + BuildPathUse.READS_DERIVED_OUTPUT + " with the same rigour. The "
                + "declarations live in " + SurvivingDataNotInBuildGuardTest.class.getSimpleName() + ".DECLARED");

        // The declarations may not decay into stale permissions: a declared site that no longer exists must be
        // removed, or the list slowly becomes a blanket exemption nobody reviews. This is also the scan's positive
        // control, since only a scan that really reached those files and really matched can satisfy it.
        for (String declared : DECLARED.keySet()) {
            assertTrue(seen.contains(declared), () -> "\"" + declared + "\" is declared in DECLARED but no source "
                    + "constructs it any more — delete the entry so the list keeps meaning what it says");
        }
    }

    /**
     * A path in this tree never contains whitespace; an assertion message that happens to mention {@code build/}
     * always does. Without this the API window alone produces false positives — the first Java file the fixed
     * comment stripper made visible was one: a `.gitignore must keep ignoring build/, so …` message sitting a
     * few lines under an unrelated `resolve(` call. A genuine path with a space would be missed, which is the
     * recall this buys the precision with, and none exists here.
     */
    private static boolean looksLikeAPath(String literal) {
        return literal.chars().noneMatch(Character::isWhitespace);
    }

    private static void classify(String literal, Path source, List<String> seen, List<String> undeclared) {
        seen.add(literal);
        if (!DECLARED.containsKey(literal)) {
            undeclared.add(CHECKOUT.relative(source) + " -> \"" + literal + "\"");
        }
    }

    /** True when a path-constructing call sits close enough before [start] to own the literal that begins there. */
    private static boolean constructedAsPath(String code, int start) {
        String window = code.substring(Math.max(0, start - API_WINDOW), start);
        return PATH_APIS.stream().anyMatch(window::contains);
    }

    /**
     * Blank out comments, keeping string literals and every character position intact.
     *
     * <p>Stripping is what lets the rule apply to CODE only: without it, a doc comment illustrating the pattern is
     * indistinguishable from a write, and the previous guard had to delete its own illustration to stay green.
     * Kotlin block comments nest, so the depth is counted rather than closed on the first {@code *}{@code /}.
     */
    static String withoutComments(String source, boolean nestsBlockComments) {
        var out = new StringBuilder(source.length());
        int blockDepth = 0;
        boolean lineComment = false;
        boolean inString = false;
        boolean inRawString = false;
        boolean inChar = false;
        for (int i = 0; i < source.length(); i++) {
            char c = source.charAt(i);
            String rest2 = i + 2 <= source.length() ? source.substring(i, i + 2) : "";
            boolean rest3IsTripleQuote = i + 3 <= source.length() && source.startsWith("\"\"\"", i);
            if (lineComment) {
                if (c == '\n') {
                    lineComment = false;
                    out.append(c);
                } else {
                    out.append(' ');
                }
            } else if (blockDepth > 0) {
                if (nestsBlockComments && "/*".equals(rest2)) {
                    blockDepth++;
                    out.append("  ");
                    i++;
                } else if ("*/".equals(rest2)) {
                    blockDepth--;
                    out.append("  ");
                    i++;
                } else {
                    out.append(c == '\n' ? c : ' ');
                }
            } else if (inRawString) {
                out.append(c);
                if (rest3IsTripleQuote) {
                    out.append("\"\"");
                    i += 2;
                    inRawString = false;
                }
            } else if (inString) {
                out.append(c);
                if (c == '\\' && i + 1 < source.length()) {
                    out.append(source.charAt(i + 1));
                    i++;
                } else if (c == '"') {
                    inString = false;
                }
            } else if (inChar) {
                out.append(c);
                if (c == '\\' && i + 1 < source.length()) {
                    out.append(source.charAt(i + 1));
                    i++;
                } else if (c == '\'') {
                    inChar = false;
                }
            } else if ("//".equals(rest2)) {
                lineComment = true;
                out.append("  ");
                i++;
            } else if ("/*".equals(rest2)) {
                blockDepth = 1;
                out.append("  ");
                i++;
            } else if (rest3IsTripleQuote) {
                inRawString = true;
                out.append("\"\"\"");
                i += 2;
            } else if (c == '"') {
                inString = true;
                out.append(c);
            } else if (c == '\'') {
                inChar = true;
                out.append(c);
            } else {
                out.append(c);
            }
        }
        return out.toString();
    }

    /**
     * The discriminator for the language rule, because getting it wrong is silent in the dangerous direction.
     *
     * Kotlin nests block comments; Java does not. Under Kotlin's rule one {@code /*} inside a Javadoc — and
     * {@code build/}{@code *-red.log} is a real occurrence in this repository — drives the depth to 2, so the
     * closing delimiter only returns it to 1 and the REST OF THE FILE reads as comment. Measured before the fix:
     * 10 Java files ended in a non-neutral state, 1,179 lines of real code blanked, and the scan reported clean.
     *
     * <p>The fixture is assembled by concatenation on purpose: written as one literal, {@code "build/planted.txt"}
     * would be a genuine match in THIS file and the scan would flag its own test data.
     */
    @Test
    void aJavadocContainingASlashStarDoesNotSwallowTheRestOfAJavaFile() {
        String planted = "\"build" + "/planted.txt\"";
        String source = "/** {@code build" + "/*-red.log} */\nclass X { void m() { Path.of(" + planted + "); } }";

        assertTrue(withoutComments(source, false).contains(planted),
                "under Java's rule the code after the Javadoc must survive, or a write site there is invisible");
        assertTrue(!withoutComments(source, true).contains(planted),
                "…and Kotlin's rule is what hid it: this half pins the discriminator, so the fix cannot be "
                        + "undone without the test noticing");
    }

    /**
     * The positive half: the record's own home must be a real committed directory. A guard that only forbids the
     * wrong location would pass just as well if the record were not written anywhere at all.
     */
    @Test
    void thePerformanceRecordHasACommittedHome() throws IOException, InterruptedException {
        Path results = CHECKOUT.resolve("perf-results");
        assertTrue(Files.isDirectory(results), "perf-results/ must exist as the committed home of the performance "
                + "record; the gate's observations are read back across runs, so they cannot be derived output");

        // Asked of a real record FILE, not of the directory. `git check-ignore perf-results` exits 1 ("not
        // ignored") even when a rule such as `perf-results/**/*.jsonl` ignores everything inside it, so the
        // directory-level question passes in precisely the state this assertion exists to catch.
        // The FILESYSTEM is the right denominator here, uniquely among this file's scans: both assertions below
        // are ABOUT untracked records. The un-ignorable check must reach the record a rule would swallow NEXT,
        // and the tracked-at-least-once check is deliberately satisfied by a minority, since most gate runs leave
        // their record untracked. Taking the set from git would make the second trivially true and hide from the
        // first exactly the file it exists to protect.
        List<Path> records;
        try (Stream<Path> walk = Files.walk(results)) {
            records = walk.filter(p -> p.getFileName().toString().endsWith(".jsonl")).toList();
        }
        assertTrue(!records.isEmpty(), "perf-results/ must hold at least one recorded run: a guard that only forbids "
                + "the wrong location would pass just as well if the record were written nowhere at all");

        // EVERY record must be un-ignorable, not one sampled arbitrarily. `--no-index` is load-bearing: by
        // default check-ignore consults the index and reports a TRACKED path as not-ignored even when a rule
        // matches it, so without this flag the assertion cannot see a rule that would swallow the NEXT record.
        // Found by planting `perf-results/**/*.jsonl` and watching the guard stay green.
        for (Path record : records) {
            String relative = CHECKOUT.relative(record);
            assertEquals(1, git("check-ignore", "-q", "--no-index", relative.toString()),
                    "git must NOT ignore " + relative + " (exit 1 means 'not ignored'); an ignored record is the "
                            + "same defect as one under a cleaned directory, just harder to notice");
        }

        // At least one must be TRACKED — but NOT all of them, and the difference is the whole point. Every gate
        // run writes a file here and perf-results/README.md says most of those stay untracked and are swept with
        // `git clean`; requiring each one to be committed would fail on any machine that had just measured
        // anything, which is precisely when a developer is least inclined to trust a guard. What must hold is
        // that the record has a COMMITTED home, so a reader who did not run the measurement can still find one.
        var tracked = new ArrayList<String>();
        for (Path record : records) {
            String relative = CHECKOUT.relative(record);
            if (git("ls-files", "--error-unmatch", relative.toString()) == 0) {
                tracked.add(relative.toString());
            }
        }
        assertTrue(!tracked.isEmpty(), "none of the " + records.size() + " record file(s) under perf-results/ is "
                + "tracked, so the whole tree is one `git clean` from empty and invisible to anyone who did not "
                + "run the measurement — commit the runs an anchor or a checkpoint cites");
    }

    /** @return the exit status, so a guard can assert on "not ignored" (1) as well as on success (0). */
    private static int git(String... arguments) throws IOException, InterruptedException {
        var command = new ArrayList<String>(List.of("git"));
        command.addAll(List.of(arguments));
        Process process = CHECKOUT.command(command)
                .redirectErrorStream(true).redirectOutput(ProcessBuilder.Redirect.DISCARD).start();
        return process.waitFor();
    }
}
