package io.github.mbackschat.a12.dm;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

import org.junit.jupiter.api.Test;

/**
 * <b>Data that must survive a build never lives under {@code build/}</b> (CLAUDE.md, owner rule 2026-08-11).
 *
 * <p><b>Why a guard rather than a note.</b> A {@code build/} directory is gitignored and deleted by {@code clean},
 * so anything written there is gone at the next clean and invisible to git. That is correct for derived output and
 * catastrophic for a record. It shipped exactly once: the performance gate wrote every measured median to
 * {@code adapter/build/perf-observations.jsonl}, which meant the estate could compare a run against one committed
 * anchor but could never compare it against its own history, because the history was deleted on a schedule. The
 * fix was to move the record; this guard is what stops the next one.
 *
 * <p><b>The rule as enforced.</b> Every source-level construction of a path under {@code build/} must be declared
 * in {@link #TRANSIENT} with a reason saying why losing it is harmless. An undeclared one fails, with the two ways
 * out named in the message: move the write to a committed directory, or declare it transient. This is the
 * classify-or-fail shape the CLI's contract exemptions already use, so a new site cannot pass silently.
 *
 * <p>The allowlist is also asserted to be <b>fully used</b>: if a declared site disappears, the entry must go too,
 * which keeps the list from decaying into a set of stale permissions that quietly widen the rule.
 */
class SurvivingDataNotInBuildGuardTest {

    /** A path literal under {@code build/} whose loss is harmless, with the reason it is harmless. */
    private static final Map<String, String> TRANSIENT = new LinkedHashMap<>(Map.of(
            "build/perf-progress.log",
            "a tailable live progress log, truncated once per JVM so each run starts clean; it exists because "
                    + "Gradle buffers captured stdout until a task ends, and it carries no measurement",
            "build/rp-large.dm.json",
            "a generated fixture for a manual before/after CLI comparison under -Drp.perf=true; regenerated by "
                    + "the test that consumes it"));

    /**
     * A {@code build/…} literal handed to a {@code File} or {@code Path.of} constructor. Requiring the constructor
     * is what keeps prose out: a doc comment or a message that merely names such a path is not a write. The pattern
     * is deliberately not illustrated with a literal example here, because this file is scanned like every other.
     */
    private static final Pattern BUILD_PATH =
            Pattern.compile("(?:File|Path\\.of)\\(\\s*\"([^\"]*build/[^\"]+)\"");

    private static Path repoRoot() {
        for (Path candidate = Path.of("").toAbsolutePath(); candidate != null; candidate = candidate.getParent()) {
            if (Files.exists(candidate.resolve("settings.gradle"))) {
                return candidate;
            }
        }
        throw new IllegalStateException("cannot locate the repository root from " + Path.of("").toAbsolutePath());
    }

    private static List<Path> sources() throws IOException {
        try (Stream<Path> walk = Files.walk(repoRoot())) {
            return walk.filter(Files::isRegularFile)
                    .filter(p -> {
                        String s = p.toString();
                        return (s.endsWith(".kt") || s.endsWith(".java"))
                                && !s.contains("/build/") && !s.contains("/.git/") && !s.contains("/.gradle/")
                                && !s.contains("/.claude/");
                    })
                    .toList();
        }
    }

    @Test
    void noSourceWritesSurvivingDataUnderBuild() throws IOException {
        var undeclared = new ArrayList<String>();
        var seen = new ArrayList<String>();
        for (Path source : sources()) {
            Matcher found = BUILD_PATH.matcher(Files.readString(source));
            while (found.find()) {
                String literal = found.group(1);
                seen.add(literal);
                if (!TRANSIENT.containsKey(literal)) {
                    undeclared.add(repoRoot().relativize(source) + " -> \"" + literal + "\"");
                }
            }
        }

        assertTrue(undeclared.isEmpty(), () -> "a build/ directory is gitignored and deleted by `clean`, so data "
                + "written there cannot survive and cannot be compared against its own history (CLAUDE.md: never "
                + "store surviving data under build/). Undeclared write site(s):\n  " + String.join("\n  ", undeclared)
                + "\n\nTwo ways out: write it to a COMMITTED directory (the performance record's own fix was "
                + "perf-results/), or, if losing it is genuinely harmless, declare it in "
                + SurvivingDataNotInBuildGuardTest.class.getSimpleName() + ".TRANSIENT with the reason why");

        // The allowlist may not decay into stale permissions: a declared site that no longer exists must be removed,
        // or the list slowly becomes a blanket exemption nobody reviews.
        for (String declared : TRANSIENT.keySet()) {
            assertTrue(seen.contains(declared), () -> "\"" + declared + "\" is declared transient but no source "
                    + "writes it any more — delete the entry so the allowlist keeps meaning what it says");
        }
    }

    /**
     * The positive half: the record's own home must be a real committed directory. A guard that only forbids the
     * wrong location would pass just as well if the record were not written anywhere at all.
     */
    @Test
    void thePerformanceRecordHasACommittedHome() throws IOException, InterruptedException {
        Path results = repoRoot().resolve("perf-results");
        assertTrue(Files.isDirectory(results), "perf-results/ must exist as the committed home of the performance "
                + "record; the gate's observations are read back across runs, so they cannot be derived output");

        Process ignored = new ProcessBuilder("git", "check-ignore", "-q", "perf-results")
                .directory(repoRoot().toFile()).start();
        assertEquals(1, ignored.waitFor(), "git must NOT ignore perf-results/ (exit 1 means 'not ignored'); an "
                + "ignored record is the same defect as one under build/, just harder to notice");
    }
}
