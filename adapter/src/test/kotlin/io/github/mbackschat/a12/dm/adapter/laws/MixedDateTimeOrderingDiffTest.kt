package io.github.mbackschat.a12.dm.adapter.laws

import io.github.mbackschat.a12.dm.interpreter.DmInterpreter
import io.github.mbackschat.a12.dm.interpreter.eval.newDocument
import io.github.mbackschat.a12.dm.interpreter.load.ModelLoader
import io.github.mbackschat.a12.dm.modelkit.DocumentModelDraft
import io.github.mbackschat.a12.dm.rulekit.dsl.BoundModel
import io.github.mbackschat.a12.dm.rulekit.dsl.Condition
import io.github.mbackschat.a12.dm.rulekit.dsl.Dsl
import io.github.mbackschat.a12.dm.rulekit.dsl.Rule
import io.github.mbackschat.a12.dm.rulekit.dsl.Severity
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Test
import java.util.Date
import java.util.function.Consumer

/** Exact-midnight discriminator for owner-legal DATE/DATE_TIME ordering on their common instant timeline. */
class MixedDateTimeOrderingDiffTest {

    private val base = DocumentModelDraft.named("appointment").locale("en_US")
        .rootGroup("Appointment", Consumer { root ->
            root.dateField("Day", Consumer { it.format("yyyy-MM-dd") })
                .dateTimeField("Moment", Consumer { it.format("yyyy-MM-dd'T'HH:mm:ss") })
        }).build().toJson()
    private val model = BoundModel.ofJson(base)
    private val rules = linkedMapOf(
        "DATE_LT_DT" to model.date(DAY).before(model.dateTime(MOMENT)),
        "DATE_LE_DT" to model.date(DAY).onOrBefore(model.dateTime(MOMENT)),
        "DATE_GT_DT" to model.date(DAY).after(model.dateTime(MOMENT)),
        "DATE_GE_DT" to model.date(DAY).onOrAfter(model.dateTime(MOMENT)),
        "DT_LT_DATE" to model.dateTime(MOMENT).before(model.date(DAY)),
        "DT_LE_DATE" to model.dateTime(MOMENT).onOrBefore(model.date(DAY)),
        "DT_GT_DATE" to model.dateTime(MOMENT).after(model.date(DAY)),
        "DT_GE_DATE" to model.dateTime(MOMENT).onOrAfter(model.date(DAY)),
    )
    private val modelJson = rules.entries.fold(base) { json, (code, condition) ->
        TypedRules.inject(json, rule(code, condition))
    }
    private val generated by lazy { RuntimeLaws.kernelJavaEngine(modelJson) }
    private val definition by lazy { ModelLoader.load(modelJson) }

    @Test
    fun aDateEqualsItsModelZoneMidnightForOrderingInBothDirections() {
        val expected = setOf("DATE_LE_DT", "DATE_GE_DT", "DT_LE_DATE", "DT_GE_DATE")
        val clock = Date(0)
        val kernelDocument = RuntimeLaws.doc().group(ROOT, 1)
            .field(DAY, "2025-06-23", 1, 1)
            .field(MOMENT, "2025-06-23T00:00:00", 1, 1)
        val dynamic = RuntimeLaws.messagesModern(modelJson, kernelDocument, clock)
            .map { it.code() }.filter(rules::containsKey).toSet()
        val java = generated.messagesModern(kernelDocument, clock)
            .map { it.code() }.filter(rules::containsKey).toSet()
        val interpreted = DmInterpreter(definition).validateFull(
            definition.newDocument().group(ROOT, 1)
                .field(DAY, "2025-06-23", 1, 1)
                .field(MOMENT, "2025-06-23T00:00:00", 1, 1),
        ).map { it.code }.filter(rules::containsKey).toSet()

        assertEquals(expected, dynamic, "normative dynamic-Groovy")
        assertEquals(dynamic, java, "generated Java")
        assertEquals(dynamic, interpreted, "kernel-free interpreter")
    }

    private fun rule(code: String, condition: Condition): Rule =
        model.rule(model.group(ROOT))
            .name(code)
            .errorField(model.date(DAY))
            .`when`(condition)
            .code(code)
            .severity(Severity.ERROR)
            .message(Dsl.en("Mixed temporal ordering differential."))
            .build()

    private companion object {
        const val ROOT = "/Appointment"
        const val DAY = "/Appointment/Day"
        const val MOMENT = "/Appointment/Moment"
    }
}
