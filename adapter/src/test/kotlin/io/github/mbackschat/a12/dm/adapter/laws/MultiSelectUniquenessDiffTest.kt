package io.github.mbackschat.a12.dm.adapter.laws

import io.github.mbackschat.a12.dm.interpreter.DmInterpreter
import io.github.mbackschat.a12.dm.interpreter.eval.Document
import io.github.mbackschat.a12.dm.interpreter.model.FieldDef
import io.github.mbackschat.a12.dm.interpreter.model.Kind
import io.github.mbackschat.a12.dm.interpreter.model.ModelDef
import io.github.mbackschat.a12.dm.interpreter.model.Requiredness
import io.github.mbackschat.a12.dm.modelkit.DocumentModelDraft
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

/**
 * Differential — **multi-select value uniqueness is CODEGEN-ONLY** (KERNEL-FINDINGS "multi-select value
 * uniqueness is a CODEGEN-only check"). A `usageType == "multi-select"` group's auto value-uniqueness check
 * (`FEHLER_MULTI_SELECT` = `uniqueValue`) is generated ONLY by the Groovy CODE GENERATOR
 * (`CodeGenRuleDefinition`, `GenerationType.UNIQUE_VALUE`); the kernel's md-RUNTIME service
 * (`IDocumentRtService`, the [RuntimeLaws] oracle) does NOT emit it — its `AutogeneratedRulesService` generates
 * the mandatory / index / solitary autogen rules, but has **no multi-select method at all**.
 *
 * The interpreter's oracle IS that runtime service, so it (correctly) treats a multi-select group as a plain
 * repeatable group and fires NO `uniqueValue` — matching the oracle exactly. This test LOCKS that: against a
 * duplicate-selection document the runtime emits no `uniqueValue`, the interpreter agrees on the FULL message
 * set, and (so the check isn't vacuous) the runtime DOES still emit the mandatory autogen on an empty required
 * row — proving the runtime autogen path is active, just multi-select-less.
 *
 * Re-open trigger: a kernel upgrade that adds multi-select to `AutogeneratedRulesService` (then the runtime
 * oracle would fire `uniqueValue` and the interpreter must too).
 */
class MultiSelectUniquenessDiffTest {

    // Authored ONCE via the typed builder (dogfood): /Order (root) → /Order/Channels (repeatable multi-select)
    // → /Order/Channels/Value (the required selectable string field).
    private val model = DocumentModelDraft.named("order").locale("en_US")
        .rootGroup("Order") { g -> g.multiSelectGroup("Channels") { ms -> ms.stringField("Value").maxRows(999) } }
        .build().toJson()

    // The interpreter loads the multi-select group as a PLAIN repeatable group (no usageType handling) — exactly
    // what the runtime oracle does. The required field still drives `mandatoryField` parity.
    private val def = ModelDef(
        listOf(FieldDef(VALUE, Kind.STRING, required = Requiredness.ABSOLUTE)),
        emptyList(),
        repeatableGroups = setOf("/Order/Channels"),
        declaredReps = mapOf("/Order/Channels" to 999),
    )

    /** Builds the SAME instance into both engines; a null value models an empty (unselected) required row. */
    private inner class Build {
        val kDoc = RuntimeLaws.doc().group("/Order", 1)
        val iDoc = Document(def.kinds, def.declaredReps, def.unsignedFields, def.rangeConfig, def.dateFormats)
        fun row(i: Int, value: String?) {
            kDoc.group("/Order/Channels", 1, i); iDoc.group("/Order/Channels", 1, i)
            if (value != null) { kDoc.field(VALUE, value, 1, i, 1); iDoc.field(VALUE, value, 1, i, 1) }
        }
    }

    @Test fun runtimeFiresNoUniqueValueAndTheInterpreterMatchesExactly() {
        // rows 1+2 duplicate "A"; row 3 empty (a required row) → the runtime fires mandatoryField on row 3 and
        // NOTHING for the duplicate (codegen-only). The interpreter, treating the group as plain, matches.
        val b = Build().apply { row(1, "A"); row(2, "A"); row(3, null) }
        val k = RuntimeLaws.messages(model, b.kDoc)
        val i = DmInterpreter(def).validate(b.iDoc).messages
        assertTrue(k.none { it.code == "uniqueValue" },
            "the md-runtime oracle does NOT emit uniqueValue for a duplicate multi-select value (codegen-only)")
        assertTrue(k.any { it.code == "mandatoryField" },
            "anchor: the runtime DOES emit the mandatory autogen — so the absence of uniqueValue is a genuine "
                + "runtime-vs-codegen gap, not a dead/mis-wired model")
        fun sig(cs: List<Pair<String, String>>) = cs.map { "${it.first}@${it.second}" }.sorted()
        assertEquals(sig(k.map { it.code to it.field }), sig(i.map { it.code to it.errorPath }),
            "interpreter matches the runtime oracle's full (code, pointer) set over a multi-select document")
    }

    private companion object {
        const val VALUE = "/Order/Channels/Value"
    }
}
